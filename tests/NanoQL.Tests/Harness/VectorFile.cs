using System.Text.Json;

namespace NanoQL.Tests.Harness;

/// <summary>
/// One committed vector file, <c>tests/vectors/&lt;path&gt;.json</c> (docs/porting-playbook.md §7.2), with its output
/// count: an array counts its elements, and a <c>{value, scale}</c> object or a <c>{"throws": true}</c> counts once.
/// A file carries one pin field: <c>"quantlib"</c>, the wheel's or the C++ harness's QuantLib, or <c>"qlnet"</c>, the
/// QLNet release of a file under <c>qlnet/</c>.
/// </summary>
public sealed class VectorFile
{
    private VectorFile(string path, JsonDocument document)
    {
        Path = path;
        JsonElement root = document.RootElement;
        Upstream = root.GetProperty("upstream").GetString();
        QuantLib = root.TryGetProperty("quantlib", out JsonElement quantLib) ? quantLib.GetString()! : null;
        QLNet = root.TryGetProperty("qlnet", out JsonElement qlnet) ? qlnet.GetString()! : null;
        if ((QuantLib is null) == (QLNet is null))
        {
            throw new InvalidOperationException($"{path}: a vector file carries one pin field, quantlib or qlnet");
        }

        Generator = root.GetProperty("generator").GetString()!;
        Seed = root.GetProperty("seed").GetInt64();
        var cases = new List<VectorCase>();
        int index = 0;
        foreach (JsonElement c in root.GetProperty("cases").EnumerateArray())
        {
            var vectorCase = new VectorCase(index++, c);
            cases.Add(vectorCase);
            foreach (JsonProperty output in vectorCase.Expected.EnumerateObject())
            {
                (int m, int o) = Count(output.Value);
                Outputs += m;
                OverriddenOutputs += o;
            }
        }

        Cases = cases;
    }

    /// <summary>Gets the file's path under <c>tests/vectors</c>, without <c>.json</c>.</summary>
    public string Path { get; }

    /// <summary>
    /// Gets the QuantLib or QLNet file the vectors check, or <see langword="null"/> for the harness's own.
    /// </summary>
    public string? Upstream { get; }

    /// <summary>
    /// Gets the QuantLib version that generated the file: the wheel's, or for a C++ harness vector the library's; or
    /// <see langword="null"/> for a QLNet file.
    /// </summary>
    public string? QuantLib { get; }

    /// <summary>Gets the QLNet release that generated a file under <c>qlnet/</c>, or <see langword="null"/>.</summary>
    public string? QLNet { get; }

    /// <summary>Gets the generator's path.</summary>
    public string Generator { get; }

    /// <summary>Gets the generator's seed.</summary>
    public long Seed { get; }

    /// <summary>Gets the cases, in file order.</summary>
    public IReadOnlyList<VectorCase> Cases { get; }

    /// <summary>Gets the number of outputs the file holds, M.</summary>
    public int Outputs { get; }

    /// <summary>Gets the number of outputs carrying a tolerance override, O.</summary>
    public int OverriddenOutputs { get; }

    /// <summary>
    /// Loads <c>tests/vectors/&lt;path&gt;.json</c>, which the build copies beside the test assembly: a file under
    /// <c>qlnet/</c> generated by QLNet 1.13.2, and every other by QuantLib 1.44.
    /// </summary>
    /// <param name="path">The file's path under <c>tests/vectors</c>, without <c>.json</c>.</param>
    /// <returns>The vector file.</returns>
    public static VectorFile Load(string path)
    {
        string file = System.IO.Path.Combine(AppContext.BaseDirectory, "vectors", path + ".json");
        VectorFile vectors = Parse(File.ReadAllText(file), path);
        bool qlnet = path.StartsWith("qlnet/", StringComparison.Ordinal);
        if (qlnet ? vectors.QLNet != "1.13.2" : vectors.QuantLib != "1.44")
        {
            string pin = vectors.QLNet is null ? "QuantLib " + vectors.QuantLib : "QLNet " + vectors.QLNet;
            throw new InvalidOperationException(
                $"{path}: generated by {pin}, not {(qlnet ? "QLNet 1.13.2" : "QuantLib 1.44")}");
        }

        return vectors;
    }

    /// <summary>Reads a vector file from its text.</summary>
    /// <param name="json">The file's JSON.</param>
    /// <param name="path">A name for messages.</param>
    /// <returns>The vector file.</returns>
    public static VectorFile Parse(string json, string path = "inline") => new(path, JsonDocument.Parse(json));

    private static (int Outputs, int Overridden) Count(JsonElement expected)
    {
        switch (expected.ValueKind)
        {
            case JsonValueKind.Array:
                int m = 0, o = 0;
                foreach (JsonElement e in expected.EnumerateArray())
                {
                    (int dm, int d0) = Count(e);
                    m += dm;
                    o += d0;
                }

                return (m, o);
            case JsonValueKind.Object:
                if (expected.TryGetProperty("throws", out _))
                {
                    return (1, 0);
                }

                if (expected.TryGetProperty("value", out _))
                {
                    return (1, expected.TryGetProperty("tolerance", out _) ? 1 : 0);
                }

                throw new InvalidOperationException($"an expected value is a scalar, an array, {{value, scale}} or {{throws}}: {expected}");
            default:
                return (1, 0);
        }
    }
}
