using NanoQL.Numerics;

namespace NanoQL.Currencies;

/// <summary>The Japanese yen.</summary>
/// <remarks>The ISO three-letter code is JPY; the numeric code is 392. It is divided into 100 sen.</remarks>
public sealed class JPYCurrency : Currency
{
    // Built once and shared by every instance, as QuantLib's static data is.
    private static readonly Rounding DataRounding = new();

    /// <summary>Initializes a new instance of the <see cref="JPYCurrency"/> class.</summary>
    public JPYCurrency()
        : base("Japanese yen", "JPY", 392, "\u00A5", "", 100, DataRounding)
    {
    }
}
