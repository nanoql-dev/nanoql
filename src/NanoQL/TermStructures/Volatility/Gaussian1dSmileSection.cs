using NanoQL.Indexes;
using NanoQL.Instruments;
using NanoQL.Models;
using NanoQL.PricingEngines;
using NanoQL.Time;
using static NanoQL.PricingEngines.BlackFormulaFunctions;

namespace NanoQL.TermStructures;

/// <summary>
/// A smile section generated by a Gaussian1d model: on a swap index, the model's swaption prices on the swap rate
/// fixing on the section's date, per unit of annuity; on an Ibor index, its caplet prices per unit of the caplet's
/// accrued discount. Its volatility is the lognormal one implied from them, 0 where it can't be implied.
/// </summary>
/// <remarks>
/// <para>
/// If curves are attached to the index, the engine's default discounting uses them; if not, the model's curve. The
/// at-the-money level and the annuity are computed at construction under the context given, which the section keeps
/// for its prices. An engine is a function, nanoql's engines being static: by default QuantLib's, the Gaussian1d
/// swaption engine on the swap index's discounting curve or the cap/floor engine on the model curve, 64 points a side
/// and 7 standard deviations.
/// </para>
/// <para>
/// Two of QuantLib's defects are fixed. QuantLib's caplet starts on the fixing date, so it fixes two business days
/// before the date of the forward it is quoted against; here it starts on the fixing's value date. And QuantLib 1.44
/// refuses every section on an Ibor index ("cannot calculate ATM without a BlackCapFloorEngine or
/// BachelierCapFloorEngine"): the caplet its annuity reads is built without a strike or an engine, which its builder
/// needs for the at-the-money strike; here it is struck at the forward, the annuity reading only its dates. On an index
/// without a forwarding curve the level is the model curve's, and the prices are refused as QuantLib's caplet refuses
/// them.
/// </para>
/// </remarks>
public sealed class Gaussian1dSmileSection : SmileSection
{
    private readonly double atm;
    private readonly double annuity;
    private readonly Date fixingDate;
    private readonly SwapIndex? swapIndex;
    private readonly IborIndex? iborIndex;
    private readonly EvaluationContext context;
    private readonly Func<Swaption, EvaluationContext, InstrumentResults>? swaptionEngine;
    private readonly Func<CapFloor, EvaluationContext, InstrumentResults>? capEngine;

    /// <summary>Initializes a new instance of the <see cref="Gaussian1dSmileSection"/> class on a swap index.</summary>
    /// <param name="fixingDate">The swap rate's fixing date.</param>
    /// <param name="swapIndex">The swap index.</param>
    /// <param name="model">The model.</param>
    /// <param name="dc">The day counter of the exercise time.</param>
    /// <param name="context">The evaluation context, which the section keeps.</param>
    /// <param name="swaptionEngine">The swaption engine, or <see langword="null"/> for QuantLib's default.</param>
    /// <exception cref="ArgumentNullException">An argument but the engine is null.</exception>
    /// <exception cref="ArgumentException">The fixing date is before the model curve's reference date.</exception>
    public Gaussian1dSmileSection(
        Date fixingDate,
        SwapIndex swapIndex,
        Gaussian1dModel model,
        DayCounter dc,
        EvaluationContext context,
        Func<Swaption, EvaluationContext, InstrumentResults>? swaptionEngine = null)
        : base(fixingDate, dc, ModelOf(model).TermStructure.ReferenceDate)
    {
        ArgumentNullException.ThrowIfNull(swapIndex);
        ArgumentNullException.ThrowIfNull(context);
        this.fixingDate = fixingDate;
        this.swapIndex = swapIndex;
        this.context = context;

        atm = model.SwapRate(fixingDate, swapIndex.Tenor, context, null, 0.0, swapIndex);
        annuity = model.SwapAnnuity(fixingDate, swapIndex.Tenor, context, null, 0.0, swapIndex);

        YieldTermStructure? discounting = swapIndex.DiscountingTermStructure;
        this.swaptionEngine = swaptionEngine
            ?? ((s, c) => Gaussian1dSwaptionEngine.Calculate(s, c, model, 64, 7.0, true, false, discounting));
    }

    /// <summary>Initializes a new instance of the <see cref="Gaussian1dSmileSection"/> class on an Ibor
    /// index.</summary>
    /// <param name="fixingDate">The rate's fixing date.</param>
    /// <param name="iborIndex">The Ibor index.</param>
    /// <param name="model">The model.</param>
    /// <param name="dc">The day counter of the exercise time.</param>
    /// <param name="context">The evaluation context, which the section keeps.</param>
    /// <param name="capEngine">The cap/floor engine, or <see langword="null"/> for QuantLib's default.</param>
    /// <exception cref="ArgumentNullException">An argument but the engine is null.</exception>
    /// <exception cref="ArgumentException">The fixing date is before the model curve's reference date.</exception>
    public Gaussian1dSmileSection(
        Date fixingDate,
        IborIndex iborIndex,
        Gaussian1dModel model,
        DayCounter dc,
        EvaluationContext context,
        Func<CapFloor, EvaluationContext, InstrumentResults>? capEngine = null)
        : base(fixingDate, dc, ModelOf(model).TermStructure.ReferenceDate)
    {
        ArgumentNullException.ThrowIfNull(iborIndex);
        ArgumentNullException.ThrowIfNull(context);
        this.fixingDate = fixingDate;
        this.iborIndex = iborIndex;
        this.context = context;

        atm = model.ForwardRate(fixingDate, context, null, 0.0, iborIndex);
        // struck at the forward, the strike unread: QuantLib builds it struck at the money without an engine that gives
        // its curve, which its builder refuses for every index
        CapFloor c = Caplet(CapFloorType.Cap, atm);
        annuity = iborIndex.DayCounter.YearFraction(c.StartDate(), c.MaturityDate()) * model.Zerobond(c.MaturityDate());

        // use model curve as discounting curve
        this.capEngine = capEngine ?? ((cf, ctx) => Gaussian1dCapFloorEngine.Calculate(cf, ctx, model, 64, 7.0, true, false));
    }

    /// <summary>The minimum strike: 0, the section being lognormal.</summary>
    /// <returns>The strike.</returns>
    public override double MinStrike() => 0.0;

    /// <summary>The maximum strike: the largest real.</summary>
    /// <returns>The strike.</returns>
    public override double MaxStrike() => NumericLimits.QL_MAX_REAL;

    /// <summary>The at-the-money level: the model's swap rate or forward rate at the fixing.</summary>
    /// <returns>The level.</returns>
    public override double? AtmLevel() => atm;

    /// <summary>The model's price of an option on the rate, per unit of annuity, times the discount.</summary>
    /// <param name="strike">The strike.</param>
    /// <param name="type">Call (a payer swaption or a cap) or put.</param>
    /// <param name="discount">The discount factor.</param>
    /// <returns>The price.</returns>
    /// <exception cref="ArgumentOutOfRangeException"><paramref name="type"/> isn't a member of its type.</exception>
    public override double OptionPrice(double strike, OptionType type = OptionType.Call, double discount = 1.0)
    {
        EnumArguments.Check(type, nameof(type));
        if (swapIndex is not null)
        {
            Swaption s = new MakeSwaption(swapIndex, fixingDate, strike)
                .WithUnderlyingType(type == OptionType.Call ? SwapType.Payer : SwapType.Receiver)
                .ToSwaption(context);
            double tmp = swaptionEngine!(s, context).NPV!.Value;
            return tmp / annuity * discount;
        }
        else
        {
            CapFloor c = Caplet(type == OptionType.Call ? CapFloorType.Cap : CapFloorType.Floor, strike);
            double tmp = capEngine!(c, context).NPV!.Value;
            return tmp / annuity * discount;
        }
    }

    /// <summary>The lognormal volatility implied from the out-of-the-money price at a strike, 0 where it can't be
    /// implied, as QuantLib's catches every failure.</summary>
    /// <param name="strike">The strike.</param>
    /// <returns>The volatility.</returns>
    protected override double VolatilityImpl(double strike)
    {
        double vol = 0.0;
        try
        {
            OptionType type = strike >= atm ? OptionType.Call : OptionType.Put;
            double o = OptionPrice(strike, type);
            vol = BlackFormulaImpliedStdDev(type, strike, atm, o) / Math.Sqrt(ExerciseTime);
        }
        catch (Exception e) when (e is ArgumentException or NanoQLException)
        {
            // QuantLib's catch (...)
        }

        return vol;
    }

    private static Gaussian1dModel ModelOf(Gaussian1dModel model)
    {
        ArgumentNullException.ThrowIfNull(model);
        return model;
    }

    // The index's caplet on the section's fixing: from the fixing's value date, where QuantLib's starts on the fixing
    // date.
    private CapFloor Caplet(CapFloorType type, double? strike) =>
        new MakeCapFloor(type, iborIndex!.Tenor, iborIndex)
            .WithStrike(strike)
            .WithEffectiveDate(iborIndex.ValueDate(fixingDate), false)
            .ToCapFloor(context);
}
