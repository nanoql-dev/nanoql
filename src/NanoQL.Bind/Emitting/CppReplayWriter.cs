using System.Globalization;
using System.Text;
using NanoQL.Bind.Model;

namespace NanoQL.Bind.Emitting;

/// <summary>
/// Writes the C++ replayer's dispatch (bindings/cpp/replay/): per C function a handler that reads its recorded arguments
/// as its C++ member's parameters (bindings/cpp/replay/replay.hpp's readers), calls the member through
/// <c>nanoql.hpp</c>, and checks the status and the result against the recorded ones; the handlers spread over files
/// compiled apart, each with its part of the table by name. Generated at build, never checked in.
/// </summary>
/// <param name="cpp">The C++ back end, whose plan names each function's member.</param>
internal sealed class CppReplayWriter(CppWriter cpp)
{
    /// <summary>The files a dispatch is spread over.</summary>
    public const int Parts = 16;

    /// <summary>The dispatch's files by name.</summary>
    /// <returns>Each file's text, LF line endings.</returns>
    public Dictionary<string, string> Write()
    {
        var functions = cpp.Members.Values
            .Where(m => m.Function.Prefix == "nql" && m.Function.Kind is not ("bind" or "bindon") && !m.Function.Params.Any(p => p.Kind.Name == "engine"))
            .OrderBy(m => m.Function.CName, StringComparer.Ordinal).ToList();
        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        for (int part = 0; part < Parts; part++)
        {
            var c = new StringBuilder();
            c.AppendLine("// The C++ replayer's handlers, generated by nanoql-bind; do not edit.");
            c.AppendLine("#include \"replay.hpp\"").AppendLine();
            c.AppendLine("using namespace nanoql;").AppendLine("using namespace replay;").AppendLine();
            var table = new List<(string Name, string Handler, bool Experimental)>();
            for (int i = part; i < functions.Count; i += Parts)
            {
                CppMember m = functions[i];
                string h = "h" + i.ToString(CultureInfo.InvariantCulture);
                bool exp = m.Function.Experimental || cpp.IsExperimentalClass(m.Function.Type);
                if (exp)
                {
                    c.AppendLine("#ifdef NANOQL_EXPERIMENTAL");
                }

                Handler(c, m, h);
                if (exp)
                {
                    c.AppendLine("#endif");
                }

                table.Add((m.Function.CName, h, exp));
            }

            string p = part.ToString(CultureInfo.InvariantCulture);
            c.AppendLine("namespace replay {").AppendLine($"extern const entry table_{p}[] = {{");
            foreach ((string name, string handler, bool exp) in table)
            {
                c.Append(exp ? "#ifdef NANOQL_EXPERIMENTAL\n" : string.Empty).AppendLine($"    {{\"{name}\", {handler}}},").Append(exp ? "#endif\n" : string.Empty);
            }

            c.AppendLine("    {nullptr, nullptr},").AppendLine("};").AppendLine("}  // namespace replay");
            files[$"dispatch_{p}.cpp"] = c.ToString().ReplaceLineEndings("\n");
        }

        var t = new StringBuilder();
        t.AppendLine("// The C++ replayer's table: its parts, generated by nanoql-bind; do not edit.");
        t.AppendLine("#include \"replay.hpp\"").AppendLine().AppendLine("namespace replay {");
        for (int part = 0; part < Parts; part++)
        {
            t.AppendLine($"extern const entry table_{part.ToString(CultureInfo.InvariantCulture)}[];");
        }

        t.AppendLine("const entry* const tables[] = {" + string.Join(", ", Enumerable.Range(0, Parts).Select(k => "table_" + k.ToString(CultureInfo.InvariantCulture))) + ", nullptr};");
        t.AppendLine("}  // namespace replay");
        files["dispatch_table.cpp"] = t.ToString().ReplaceLineEndings("\n");
        return files;
    }

    // One handler: the arguments read, the stop checked, the member called, its result and in-out arguments checked.
    private void Handler(StringBuilder c, CppMember m, string h)
    {
        CFunction f = m.Function;
        c.AppendLine($"static int {h}(rp& r, const jv* a, const jv* res, int t)").AppendLine("{");
        var after = new List<string>();
        int j = 0;
        if (f.Params.Count > 0 && f.Params[0].IsSelf)
        {
            c.AppendLine(m.Value
                ? $"    {m.Class} self = r.{(m.Class == "Date" ? "date" : "period")}(a, 0);"
                : $"    {m.Class} self = r.obj<{m.Class}>(a, 0);");
            j = 1;
        }

        var args = new List<string>();
        foreach (CParam p in f.Params.Where(p => !p.IsSelf))
        {
            string n = "p" + j.ToString(CultureInfo.InvariantCulture);
            string type = m.Types[args.Count];
            Read(c, p, type, n, j, after);
            args.Add(n);
            j++;
        }

        c.AppendLine("    if (r.stop) return 0;");
        string call = m.Style switch
        {
            "new" => $"{m.Class}({string.Join(", ", args)})",
            "static" => $"{m.Class}::{m.Name}({string.Join(", ", args)})",
            "index" => $"self[{args[0]}]",
            _ => $"self.{m.Name}({string.Join(", ", args)})",
        };
        string afterChecks = string.Concat(after.Select(s => " " + s));
        bool returns = m.Style == "new" || f.Kind is "bind" or "bindon" || f.Return != null;
        if (!returns)
        {
            c.AppendLine($"    return r.call_void(t, [&] {{ {call}; }}, [&] {{{afterChecks} }});");
        }
        else
        {
            string check = f.Return?.Name == "sequences" ? "check_sequences(r, res, v);" : "check(r, res, v);";
            c.AppendLine($"    return r.call(t, [&] {{ return {call}; }}, [&](const auto& v) {{ {check}{afterChecks} }});");
        }

        c.AppendLine("}").AppendLine();
    }

    // An argument read into its parameter's type: a value, an object of the parameter's class, a collection's storage
    // and its view, or an in-out vector or matrix whose values after the call are checked.
    private static void Read(StringBuilder c, CParam p, string type, string n, int j, List<string> after)
    {
        string bare = type.Replace("const ", string.Empty, StringComparison.Ordinal).TrimEnd('&');
        CKind k = p.Kind;
        switch (k.Name)
        {
            case "handle" or "boxed" or "boxed?" or "snapshot":
                c.AppendLine($"    {bare} {n} = r.obj<{bare}>(a, {j});");
                return;
            case "matrix" when bare.StartsWith("std::optional", StringComparison.Ordinal):
                c.AppendLine($"    {bare} {n} = r.opt_matrix(a, {j});");
                return;
            case "matrix" or "matrix&":
                c.AppendLine($"    Matrix {n} = r.matrix(a, {j});");
                if (k.Name == "matrix&")
                {
                    after.Add($"r.after({after.Count}, {n}.values());");
                }

                return;
            case "vector&" or "span":
            {
                string e = bare[(bare.IndexOf('<', StringComparison.Ordinal) + 1)..^1];
                c.AppendLine($"    {bare} {n} = r.required(r.vec<{e}>(a, {j}));");
                after.Add($"r.after({after.Count}, {n});");
                return;
            }

            case "vector" or "array" or "jagged" or "map":
            {
                string e = bare[(bare.IndexOf('<', StringComparison.Ordinal) + 1)..^1];
                c.AppendLine($"    auto s{j} = r.vec<{e}>(a, {j});");
                c.AppendLine($"    {bare} {n} = s{j} ? {bare}(*s{j}) : {bare}(nullptr);");
                return;
            }

            default:
                c.AppendLine($"    {bare} {n} = r.value<{bare}>(a, {j});");
                return;
        }
    }
}
