using System.Globalization;
using System.Text;
using NanoQL.Bind.Model;

namespace NanoQL.Bind.Emitting;

/// <summary>
/// Writes the Java replayer's dispatch (bindings/java/src/test/java/org/nanoql/replay/): per C function a handler that
/// reads its recorded arguments as its Java member's parameters (the replayer's <c>Rp</c> readers), calls the member
/// through the layer, and checks the status and the result against the recorded ones; the handlers spread over classes,
/// each with its names and a switch, which <c>DispatchTable</c> joins. Generated at build, never checked in.
/// </summary>
/// <param name="java">The Java back end, whose plan names each function's member.</param>
internal sealed class JavaReplayWriter(JavaWriter java)
{
    /// <summary>The classes a dispatch is spread over.</summary>
    public const int Parts = 32;

    /// <summary>The dispatch's files by their path under the test sources' root.</summary>
    /// <returns>Each file's text, LF line endings.</returns>
    public Dictionary<string, string> Write()
    {
        var functions = java.Members.Values
            .Where(m => m.Function.Prefix == "nql" && m.Function.Kind is not ("bind" or "bindon") && !m.Function.Params.Any(p => p.Kind.Name == "engine"))
            .OrderBy(m => m.Function.CName, StringComparer.Ordinal).ToList();
        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        for (int part = 0; part < Parts; part++)
        {
            string p = part.ToString(CultureInfo.InvariantCulture);
            var c = new StringBuilder();
            var names = new List<string>();
            var handlers = new StringBuilder();
            for (int i = part; i < functions.Count; i += Parts)
            {
                Handler(handlers, functions[i], "h" + names.Count.ToString(CultureInfo.InvariantCulture));
                names.Add(functions[i].Function.CName);
            }

            c.AppendLine("// The Java replayer's handlers, generated by nanoql-bind; do not edit.");
            c.AppendLine("package org.nanoql.replay;").AppendLine();
            c.AppendLine("@SuppressWarnings({\"unchecked\", \"rawtypes\", \"deprecation\", \"removal\"})");
            c.AppendLine($"final class Dispatch{p} {{");
            c.AppendLine("    static final String[] NAMES = {");
            foreach (string name in names)
            {
                c.AppendLine($"        \"{name}\",");
            }

            c.AppendLine("    };").AppendLine();
            c.AppendLine($"    private Dispatch{p}() {{").AppendLine("    }").AppendLine();
            c.AppendLine("    static int run(int k, Rp r, Jv a, Jv res, int t) {");
            c.AppendLine("        return switch (k) {");
            for (int k = 0; k < names.Count; k++)
            {
                string h = "h" + k.ToString(CultureInfo.InvariantCulture);
                c.AppendLine($"            case {k.ToString(CultureInfo.InvariantCulture)} -> {h}(r, a, res, t);");
            }

            c.AppendLine("            default -> 0;").AppendLine("        };").AppendLine("    }");
            c.Append(handlers);
            c.AppendLine("}");
            files[$"org/nanoql/replay/Dispatch{p}.java"] = c.ToString().ReplaceLineEndings("\n");
        }

        var t = new StringBuilder();
        t.AppendLine("// The Java replayer's table: its parts, generated by nanoql-bind; do not edit.");
        t.AppendLine("package org.nanoql.replay;").AppendLine();
        t.AppendLine("final class DispatchTable {");
        t.AppendLine("    static final String[][] NAMES = {" + string.Join(", ", Enumerable.Range(0, Parts).Select(k => $"Dispatch{k.ToString(CultureInfo.InvariantCulture)}.NAMES")) + "};").AppendLine();
        t.AppendLine("    private DispatchTable() {").AppendLine("    }").AppendLine();
        t.AppendLine("    static int run(int part, int k, Rp r, Jv a, Jv res, int t) {");
        t.AppendLine("        return switch (part) {");
        for (int part = 0; part < Parts; part++)
        {
            string p = part.ToString(CultureInfo.InvariantCulture);
            t.AppendLine($"            case {p} -> Dispatch{p}.run(k, r, a, res, t);");
        }

        t.AppendLine("            default -> 0;").AppendLine("        };").AppendLine("    }").AppendLine("}");
        files["org/nanoql/replay/DispatchTable.java"] = t.ToString().ReplaceLineEndings("\n");
        return files;
    }

    // One handler: the arguments read, the stop checked, the member called, its result and in-out arguments checked, the
    // objects its result brought closed unless the replay registered them.
    private void Handler(StringBuilder c, JavaMember m, string h)
    {
        CFunction f = m.Function;
        c.AppendLine().AppendLine($"    private static int {h}(Rp r, Jv a, Jv res, int t) {{");
        var after = new List<string>();
        int j = 0;
        if (f.Params.Count > 0 && f.Params[0].IsSelf)
        {
            c.AppendLine(m.Type.Form == "value"
                ? m.Type.CName == "Date" ? "        java.time.LocalDate self = r.date(a, 0);" : $"        {java.Type(new CKind("period", m.Type.Type), false)} self = r.period(a, 0);"
                : $"        {java.Fqn(m.Type)} self = r.{(m.Style == "instance" ? "self(a, " : "obj(a, 0, ")}{java.Fqn(m.Type)}.class);");
            j = 1;
        }

        var args = new List<string>();
        foreach (CParam p in f.Params.Where(p => !p.IsSelf))
        {
            string n = "p" + j.ToString(CultureInfo.InvariantCulture);
            string type = m.Types[args.Count];
            c.AppendLine($"        {type} {n} = {Read(p.Kind, type, j)};");
            if (p.Kind.Name is "matrix&" or "vector&" or "span")
            {
                after.Add($"r.after({after.Count.ToString(CultureInfo.InvariantCulture)}, {n});");
            }

            args.Add(n);
            j++;
        }

        c.AppendLine("        if (r.stop) {").AppendLine("            return 0;").AppendLine("        }");
        string list = string.Join(", ", args);
        // A record's generated equality pair, which no class declares, through equals (nql_equals), null as C#'s == takes it.
        string call = f.GeneratedEquality ? $"{(f.BaseName == "op_Inequality" ? "!" : string.Empty)}java.util.Objects.equals({args[0]}, {args[1]})" : m.Style switch
        {
            "new" => $"new {m.Holder}({list})",
            "static" => $"{m.Holder}.{m.Name}({list})",
            "self" => $"{m.Holder}.{m.Name}({string.Join(", ", args.Prepend("self"))})",
            _ => $"self.{m.Name}({list})",
        };
        bool returns = m.Style == "new" || f.Kind == "new" || f.Return != null;
        c.AppendLine("        try {");
        c.AppendLine(returns ? $"            var v = {call};" : $"            {call};");
        c.AppendLine("            if (r.ok(t)) {");
        if (returns)
        {
            c.AppendLine(f.Return != null && Dates(f.Return) ? "                r.checkDates(res, v);" : "                r.check(res, v);");
        }

        foreach (string s in after)
        {
            c.AppendLine("                " + s);
        }

        c.AppendLine("            }");
        if (returns && HoldsObjects(f))
        {
            c.AppendLine("            r.release(v);");
        }

        c.AppendLine("        } catch (RuntimeException e) {").AppendLine("            r.fail(t, e);").AppendLine("        }");
        c.AppendLine("        return 1;").AppendLine("    }");
    }

    // Whether a result can hold an object the call made: a constructor's, a handle's, a collection or tuple of them, a
    // generator's draws with their next snapshot.
    private static bool HoldsObjects(CFunction f) =>
        (f.Kind == "new" && f.Return?.Name is not ("date" or "period")) || (f.Return != null && Holds(f.Return));

    private static bool Holds(CKind k) => k.Name switch
    {
        "handle" or "boxed" or "boxed?" or "snapshot" or "draws" or "sequences" => true,
        "array" or "map" => Holds(k.Element!) || (k.Value != null && Holds(k.Value)),
        "tuple" or "tuple?" => k.Items.Any(Holds),
        _ => false,
    };

    private static bool Dates(CKind k) => k.Name is "date" or "date?" || (k.Element != null && Dates(k.Element)) || (k.Value != null && Dates(k.Value)) || k.Items.Any(Dates);

    // An argument read into its parameter's Java type.
    private string Read(CKind k, string type, int j)
    {
        string at = j.ToString(CultureInfo.InvariantCulture);
        return k.Name switch
        {
            "double" => $"r.dbl(a, {at})",
            "int32" => $"r.i32(a, {at})",
            "int64" => $"r.i64(a, {at})",
            "bool" => $"r.bool(a, {at})",
            "double?" => $"r.optDbl(a, {at})",
            "int32?" => $"r.optI32(a, {at})",
            "int64?" => $"r.optI64(a, {at})",
            "bool?" => $"r.optBool(a, {at})",
            "string" => $"r.str(a, {at})",
            "date" or "date?" => $"r.date(a, {at})",
            "period" or "period?" => $"r.period(a, {at})",
            "complex" or "complex?" => $"r.complex(a, {at})",
            "enum" or "enum?" => type == "java.lang.Integer" ? $"r.optI32(a, {at})" : $"r.enm(a, {at}, {type}.class)",
            "handle" or "boxed" or "boxed?" or "snapshot" => $"r.obj(a, {at}, {type}.class)",
            "matrix" or "matrix&" => $"r.matrix(a, {at})",
            "vector" or "vector&" => $"r.doubles(a, {at})",
            "span" => k.Element!.Name == "double" ? $"r.doubles(a, {at})" : $"r.ints(a, {at})",
            "tuple" => $"({type}) r.tuple(a, {at}, {Kinds(k)}, {Classes(k)})",
            "array" when k.Element!.Name == "tuple" => $"r.tuples(a, {at}, {Kinds(k.Element)}, {Classes(k.Element)})",
            "array" => k.Element!.Name switch
            {
                "double" => $"r.doubles(a, {at})",
                "int32" => $"r.ints(a, {at})",
                "int64" => $"r.longs(a, {at})",
                "bool" => $"r.bools(a, {at})",
                _ => $"r.list(a, {at}, \"{k.Element.Name}\", {ElementClass(k.Element)})",
            },
            "jagged" => $"r.jagged(a, {at})",
            "map" => $"r.map(a, {at}, \"{k.Element!.Name}\", {ElementClass(k.Element)}, \"{k.Value!.Name}\", {ElementClass(k.Value)})",
            _ => throw new InvalidOperationException("no Java replay reader for the kind " + k.Text),
        };
    }

    // A tuple's element kinds and classes, for the tuple readers.
    private static string Kinds(CKind t) => "new String[] {" + string.Join(", ", t.Items.Select(i => $"\"{i.Name}\"")) + "}";

    private string Classes(CKind t) => "new Class<?>[] {" + string.Join(", ", t.Items.Select(ElementClass)) + "}";

    // An element's class, for the readers that make enums and objects; null for the rest.
    private string ElementClass(CKind e) => e.Name is "enum" or "handle" or "boxed" or "boxed?" or "snapshot" ? JavaWriter.Erased(java.Type(e, true)) + ".class" : "null";
}
