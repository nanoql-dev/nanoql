using System.Security;
using System.Text;
using NanoQL.Bind.Reading;

namespace NanoQL.Bind.Emitting;

/// <summary>
/// The Excel-DNA project an Excel build generates: <c>NanoQL.Excel.Functions</c>, the generated functions its only
/// source, referencing the runtime package <c>NanoQL.Excel</c> at the tool's version and the assemblies it binds by
/// path; its <c>.dna</c> lists the runtime and the functions as external libraries, explicit exports, packed and loaded
/// from bytes, and the bound assemblies packed beside them, their PDBs apart.
/// </summary>
internal static class ExcelProject
{
    /// <summary>The project's name, and its assembly's.</summary>
    public const string Name = "NanoQL.Excel.Functions";

    /// <summary>The Excel-DNA version the add-in builds on.</summary>
    public const string ExcelDna = "1.9.0";

    /// <summary>The add-in's file name before Excel-DNA's <c>64.xll</c>: nanoql's builds' own, or a user's build's.</summary>
    /// <param name="assemblies">The bound assemblies.</param>
    /// <param name="experimental">Whether the build holds the experimental API.</param>
    /// <returns>The name.</returns>
    public static string AddInName(IReadOnlyList<AssemblyInput> assemblies, bool experimental)
    {
        var others = assemblies.Select(a => a.Prefix).Where(p => p != "nql").Distinct().ToList();
        string name = others.Count == 0 ? "nanoql" : "nanoql-" + string.Join("-", others);
        return experimental ? name + "-experimental" : name;
    }

    /// <summary>Writes the project into a folder, replacing its generated files.</summary>
    /// <param name="dir">The folder.</param>
    /// <param name="files">The generated C#, each file by its name.</param>
    /// <param name="assemblies">The bound assemblies.</param>
    /// <param name="experimental">Whether the build holds the experimental API.</param>
    /// <param name="runtimeSource">A local feed holding the runtime package, or null for NuGet's.</param>
    public static void Write(string dir, IReadOnlyDictionary<string, string> files, IReadOnlyList<AssemblyInput> assemblies, bool experimental, string? runtimeSource)
    {
        string gen = Path.Combine(dir, "gen");
        Directory.CreateDirectory(gen);
        foreach (string old in Directory.EnumerateFiles(gen, "*.g.cs"))
        {
            File.Delete(old);
        }

        foreach ((string name, string text) in files)
        {
            File.WriteAllText(Path.Combine(gen, name), text);
        }

        string shown = experimental ? "nanoql (experimental)" : "nanoql";
        var refs = new StringBuilder();
        var dna = new StringBuilder();
        foreach (string path in assemblies.Select(a => a.Path).Distinct(StringComparer.OrdinalIgnoreCase))
        {
            string file = Path.GetFileName(path);
            refs.AppendLine($"    <Reference Include=\"{Xml(Path.GetFileNameWithoutExtension(path))}\"><HintPath>{Xml(path)}</HintPath></Reference>");
            dna.AppendLine($"  <Reference Path=\"{Xml(file)}\" Pack=\"true\" />");
        }

        // A local feed (the repository, CI) restores into the build's own folder, so a runtime packed again under the same
        // version is the one restored, never a copy NuGet's global folder kept; that folder is read for the rest. The
        // folder is no item of the project's: a package restored there whole (Excel-DNA's, where NuGet's global folder
        // lacks it) brings its template .dna, which Excel-DNA would pack as a second add-in.
        string source = runtimeSource == null ? string.Empty
            : $"    <RestoreAdditionalProjectSources>{Xml(runtimeSource)}</RestoreAdditionalProjectSources>\n"
              + "    <RestorePackagesPath>$(MSBuildProjectDirectory)\\packages</RestorePackagesPath>\n"
              + "    <DefaultItemExcludes>$(DefaultItemExcludes);packages\\**</DefaultItemExcludes>\n"
              + "    <RestoreFallbackFolders Condition=\"'$(NUGET_PACKAGES)' != ''\">$(NUGET_PACKAGES)</RestoreFallbackFolders>\n"
              + "    <RestoreFallbackFolders Condition=\"'$(NUGET_PACKAGES)' == ''\">$(UserProfile)\\.nuget\\packages</RestoreFallbackFolders>\n";
        string project = $"""
            <Project Sdk="Microsoft.NET.Sdk">
              <!-- Generated by nanoql-bind excel build (docs/excel.md): the worksheet functions of the assemblies it bound, over the
                   NanoQL.Excel runtime. Rebuilt by the tool; edits are lost. -->
              <PropertyGroup>
                <TargetFramework>net10.0-windows</TargetFramework>
                <AssemblyName>{Name}</AssemblyName>
                <RootNamespace>{Name}</RootNamespace>
                <Nullable>disable</Nullable>
                <ImplicitUsings>disable</ImplicitUsings>
                <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
                <NoWarn>$(NoWarn);CS0618;CS8632;NQL0001;CA1416</NoWarn>
                <ExcelAddInName>{Xml(shown)}</ExcelAddInName>
                <ExcelAddInExplicitExports>true</ExcelAddInExplicitExports>
                <ExcelAddInIncludePdb>true</ExcelAddInIncludePdb>
                <ExcelDnaCreate32BitAddIn>false</ExcelDnaCreate32BitAddIn>
                <RunExcelDnaSetDebuggerOptions>false</RunExcelDnaSetDebuggerOptions>
            {source}  </PropertyGroup>
              <ItemGroup>
                <PackageReference Include="ExcelDna.AddIn" Version="{ExcelDna}" />
                <PackageReference Include="NanoQL.Excel" Version="{Versions.Text}" />
            {refs}    <Compile Include="gen\*.g.cs" />
                <!-- The repro templates and the adapters' source, which nqlxlRepro renders a cell's calls from. -->
                <EmbeddedResource Include="xl-templates.json" LogicalName="NanoQL.Excel.templates.json" />
                <EmbeddedResource Include="gen\XlAdapters.g.cs" LogicalName="NanoQL.Excel.adapters.cs" />
              </ItemGroup>
            </Project>

            """;
        File.WriteAllText(Path.Combine(dir, Name + ".csproj"), project.ReplaceLineEndings("\n"));
        string library = $"""
            <?xml version="1.0" encoding="utf-8"?>
            <DnaLibrary Name="{Xml(shown)}" RuntimeVersion="v10.0" xmlns="http://schemas.excel-dna.net/addin/2020/07/dnalibrary">
            {dna}  <ExternalLibrary Path="NanoQL.Excel.dll" ExplicitExports="true" LoadFromBytes="true" Pack="true" />
              <ExternalLibrary Path="{Name}.dll" ExplicitExports="true" LoadFromBytes="true" Pack="true" IncludePdb="true" />
            </DnaLibrary>

            """;
        File.WriteAllText(Path.Combine(dir, Name + "-AddIn.dna"), library.ReplaceLineEndings("\n"));

        // The project stands alone: no repository's build settings above it reach it.
        File.WriteAllText(Path.Combine(dir, "Directory.Build.props"), "<Project />\n");
        File.WriteAllText(Path.Combine(dir, "Directory.Build.targets"), "<Project />\n");
    }

    /// <summary>Writes the notices a build's add-in redistributes beside it: nanoql's, which a user's build carries too.</summary>
    /// <param name="dir">The folder.</param>
    public static void WriteNotices(string dir)
    {
        foreach (string name in new[] { "LICENSE", "NOTICE", "THIRD_PARTY_NOTICES.md" })
        {
            File.WriteAllBytes(Path.Combine(dir, name), Notice(name));
        }
    }

    /// <summary>One of nanoql's notices, as the tool carries it.</summary>
    /// <param name="name"><c>LICENSE</c>, <c>NOTICE</c> or <c>THIRD_PARTY_NOTICES.md</c>.</param>
    /// <returns>Its bytes.</returns>
    public static byte[] Notice(string name)
    {
        using Stream s = typeof(ExcelProject).Assembly.GetManifestResourceStream("NanoQL.Bind.notices." + name)
            ?? throw new InvalidOperationException($"the tool doesn't carry {name}");
        using var m = new MemoryStream();
        s.CopyTo(m);
        return m.ToArray();
    }

    private static string Xml(string s) => SecurityElement.Escape(s);
}
