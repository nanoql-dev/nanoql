using System.Text;
using NanoQL.Bind.Model;

namespace NanoQL.Bind.Emitting;

/// <summary>
/// Writes the C headers: <c>nanoql.h</c>, nanoql's C API with its fixed functions, codes, version macros and every
/// <c>nql_</c> function; and, for an assembly built on nanoql, a header of its own prefix's functions that includes
/// <c>nanoql.h</c>. An experimental declaration is compiled only under <c>NANOQL_EXPERIMENTAL</c>, C's opt-in.
/// </summary>
internal static class HeaderWriter
{
    /// <summary>The header for one prefix.</summary>
    /// <param name="surface">The surface.</param>
    /// <param name="prefix">The prefix: <c>nql</c> writes <c>nanoql.h</c>.</param>
    /// <returns>The header's text, LF line endings.</returns>
    public static string Write(Surface surface, string prefix)
    {
        bool core = prefix == "nql";
        string guard = core ? "NANOQL_H" : prefix.ToUpperInvariant() + "_H";
        var h = new StringBuilder();
        h.AppendLine("/* SPDX-FileCopyrightText: 2026 The nanoql Authors").AppendLine("   SPDX-License-Identifier: Apache-2.0").AppendLine();
        h.AppendLine(core
            ? "   nanoql.h: nanoql's C API, generated by nanoql-bind; do not edit. docs/bindings.md describes its rules: names,"
            : $"   {prefix}.h: the C API of {string.Join(", ", surface.Assemblies.Where(a => a.Prefix == prefix).Select(a => a.Assembly))}, generated by nanoql-bind; do not edit. It needs nanoql.h,");
        h.AppendLine(core
            ? "   handles, errors, values, the context and conventions, experimental functions and versions. */"
            : "   whose rules it follows (docs/bindings.md). */");
        h.AppendLine($"#ifndef {guard}").AppendLine($"#define {guard}").AppendLine();
        if (core)
        {
            h.Append(Fixed);
        }
        else
        {
            h.AppendLine("#include \"nanoql.h\"").AppendLine().AppendLine("#ifdef __cplusplus").AppendLine("extern \"C\" {").AppendLine("#endif").AppendLine();
        }

        Guarded(h, surface.Enums.Where(e => e.Prefix == prefix), e => e.Experimental, (sb, e) =>
        {
            string upper = prefix.ToUpperInvariant();
            sb.AppendLine($"/* enum {Describe.Type(e.Type)} */").AppendLine($"typedef int32_t {prefix}_{e.CName};");
            foreach ((string name, long value) in e.Members)
            {
                sb.AppendLine($"#define {upper}_{e.CName}_{name} ((int32_t){value})");
            }
        });
        h.AppendLine();
        Guarded(h, surface.Functions.Where(f => f.Prefix == prefix), f => f.Experimental, (sb, f) =>
        {
            sb.AppendLine("/* " + Describe.Of(f).Replace("*/", "* /", StringComparison.Ordinal) + " */");
            string deprecated = f.Deprecated != null ? $"NQL_DEPRECATED({System.Text.Json.JsonSerializer.Serialize(f.Deprecated)}) " : string.Empty;
            sb.AppendLine($"{deprecated}NQL_API nql_status {f.CName}({string.Join(", ", CForms.All(f).Select(s => s.CType + " " + s.Name))});");
        });
        h.AppendLine().AppendLine("#ifdef __cplusplus").AppendLine("}").AppendLine("#endif").AppendLine().AppendLine($"#endif /* {guard} */");
        return h.ToString().ReplaceLineEndings("\n");
    }

    // Declarations in order, consecutive experimental ones inside one #ifdef NANOQL_EXPERIMENTAL block.
    private static void Guarded<T>(StringBuilder h, IEnumerable<T> items, Func<T, bool> experimental, Action<StringBuilder, T> write)
    {
        bool open = false;
        foreach (T item in items)
        {
            bool e = experimental(item);
            if (e && !open)
            {
                h.AppendLine("#ifdef NANOQL_EXPERIMENTAL");
            }
            else if (!e && open)
            {
                h.AppendLine("#endif /* NANOQL_EXPERIMENTAL */");
            }

            open = e;
            write(h, item);
        }

        if (open)
        {
            h.AppendLine("#endif /* NANOQL_EXPERIMENTAL */");
        }
    }

    private static string Fixed => $$"""
        #include <stdbool.h>
        #include <stdint.h>

        /* The release this header belongs to: major and minor, a third part only for a fix. The ABI's version is the major
           times 1,000 plus the minor, which a fix keeps. The library answers nql_version() and nql_abi_version(); a program
           linking a separately installed library checks them against the header it was compiled with, as SQLite advises:
             assert(nql_abi_version() == NQL_ABI_VERSION);
           A 2.y header works with the 2.y library alone. */
        #define NQL_VERSION_MAJOR {{Versions.Major}}
        #define NQL_VERSION_MINOR {{Versions.Minor}}
        #define NQL_VERSION_PATCH {{Versions.Patch}}
        #define NQL_VERSION "{{Versions.Text}}"
        #define NQL_ABI_VERSION {{Versions.Abi}}

        #if defined(_WIN32)
        #  define NQL_API __declspec(dllimport)
        #elif defined(__GNUC__) || defined(__clang__)
        #  define NQL_API __attribute__((visibility("default")))
        #else
        #  define NQL_API
        #endif

        /* A member nanoql deprecates: removed or changed only two releases and a year after (docs/bindings.md). */
        #if defined(__GNUC__) || defined(__clang__)
        #  define NQL_DEPRECATED(message) __attribute__((deprecated(message)))
        #elif defined(_MSC_VER)
        #  define NQL_DEPRECATED(message) __declspec(deprecated(message))
        #else
        #  define NQL_DEPRECATED(message)
        #endif

        #ifdef __cplusplus
        extern "C" {
        #endif

        /* One handle type for every object. Every handle a function returns is the caller's, released once with nql_release;
           NULL is the null reference. A released, stale, never-issued or another library's handle is refused with
           NQL_ERROR_HANDLE, a handle of the wrong type with NQL_ERROR_TYPE. Any thread may use any handle at once: every
           object behind a handle is immutable. */
        typedef struct nql_object* nql_handle;

        /* Every function returns a status: 0 for success, a positive code per refusal kind. Results come back through the
           last parameters. */
        typedef int32_t nql_status;

        /* A date: QuantLib's serial number, Excel's serial date; 0 is no date (QuantLib's Date()), its first valid date 367. */
        typedef int32_t nql_date;

        /* A period: its length and its unit (NQL_TimeUnit_...), passed by value. */
        typedef struct nql_period { int32_t length; int32_t units; } nql_period;

        /* A complex number. */
        typedef struct nql_complex { double re; double im; } nql_complex;

        #define NQL_OK 0
        #define NQL_ERROR 1                    /* NanoQLException: QuantLib's own checks */
        #define NQL_ERROR_ARGUMENT 2           /* ArgumentException */
        #define NQL_ERROR_ARGUMENT_NULL 3      /* ArgumentNullException; a NULL self */
        #define NQL_ERROR_ARGUMENT_RANGE 4     /* ArgumentOutOfRangeException; a documented IndexOutOfRangeException */
        #define NQL_ERROR_INVALID_OPERATION 5  /* InvalidOperationException */
        #define NQL_ERROR_INVALID_CAST 6       /* InvalidCastException: a type argument or a calibrated model of the wrong type */
        #define NQL_ERROR_NOT_SUPPORTED 7      /* NotSupportedException */
        #define NQL_ERROR_KEY_NOT_FOUND 8      /* KeyNotFoundException */
        #define NQL_ERROR_HANDLE 9             /* a released, stale, foreign or never-issued handle */
        #define NQL_ERROR_TYPE 10              /* a handle whose object isn't of the parameter's type; a bound engine that can't serve */
        #define NQL_ERROR_OUT_OF_MEMORY 11     /* OutOfMemoryException */
        #define NQL_ERROR_IO 12                /* IOException and its kinds, UnauthorizedAccessException: a file not read or written */
        #define NQL_ERROR_FORMAT 13            /* malformed input: XmlException, XmlSchemaValidationException, FormatException */
        #define NQL_ERROR_INTERNAL 99          /* anything else: a defect in nanoql, to report */

        /* The last refusal on the calling thread: its code, message, parameter (as .NET names it, NULL for none) and .NET
           exception type. The strings are valid until the thread's next nanoql call. */
        NQL_API nql_status nql_last_error_code(void);
        NQL_API const char* nql_last_error_message(void);
        NQL_API const char* nql_last_error_param(void);
        NQL_API const char* nql_last_error_type(void);

        /* Handles. nql_retain gives a second owner: a new handle to the same object. nql_type_name gives the object's .NET
           type (a generator snapshot's, its generator's), so a layer wraps a base-typed result as its own class. */
        NQL_API nql_status nql_release(nql_handle h);
        NQL_API nql_status nql_retain(nql_handle h, nql_handle* result);
        NQL_API nql_status nql_type_name(nql_handle h, char** result);
        NQL_API nql_status nql_equals(nql_handle a, nql_handle b, bool* result);
        NQL_API nql_status nql_hash(nql_handle h, int32_t* result);
        NQL_API nql_status nql_to_string(nql_handle h, char** result);

        /* Diagnostics: the handles issued and not released. */
        NQL_API nql_status nql_live_handles(int64_t* result);

        /* Memory nanoql allocates for a caller (a string, an array) is freed with nql_free; an array of handles' handles
           are each released first. */
        NQL_API void nql_free(void* p);

        /* The library's version: its text and its ABI's version. */
        NQL_API const char* nql_version(void);
        NQL_API int32_t nql_abi_version(void);


        """;
}
