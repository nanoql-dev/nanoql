using System.Text;
using NanoQL.Bind.Model;

namespace NanoQL.Bind.Emitting;

/// <summary>
/// Writes the C replayer's dispatch, <c>dispatch.c</c>: per C function a handler that reads its recorded arguments in
/// their C forms (bindings/c/replay/replay.h's readers), calls the function, and checks its status and result against
/// the recorded ones; and the table of handlers by name, sorted, which the replayer searches. Generated at build, never
/// checked in.
/// </summary>
internal sealed class CReplayWriter(Surface surface)
{
    /// <summary>The dispatch's text.</summary>
    /// <returns>The C source, LF line endings.</returns>
    public string Write()
    {
        var c = new StringBuilder();
        c.AppendLine("/* dispatch.c: the C replayer's handlers, generated by nanoql-bind; do not edit. */");
        c.AppendLine("#include \"replay.h\"").AppendLine("#include <stddef.h>").AppendLine("#include <string.h>").AppendLine();
        foreach (string prefix in surface.Assemblies.Select(a => a.Prefix).Distinct().Where(p => p != "nql"))
        {
            c.AppendLine($"#include \"{prefix}.h\"");
        }

        var table = new List<(string Name, string Handler)>();
        for (int i = 0; i < surface.Functions.Count; i++)
        {
            CFunction f = surface.Functions[i];
            if (f.Kind is "bind" or "bindon" || f.Params.Any(p => p.Kind.Name is "engine"))
            {
                continue;
            }

            string h = "h" + i;
            if (f.Experimental)
            {
                c.AppendLine("#ifdef NANOQL_EXPERIMENTAL");
            }

            Handler(c, f, h);
            if (f.Experimental)
            {
                c.AppendLine("#endif");
            }

            table.Add((f.CName, f.Experimental ? h + "!" : h));
        }

        c.AppendLine("const replay_entry replay_table[] = {");
        foreach ((string name, string handler) in table.OrderBy(t => t.Name, StringComparer.Ordinal))
        {
            if (handler.EndsWith('!'))
            {
                c.AppendLine("#ifdef NANOQL_EXPERIMENTAL").AppendLine($"    {{\"{name}\", {handler.TrimEnd('!')}}},").AppendLine("#endif");
            }
            else
            {
                c.AppendLine($"    {{\"{name}\", {handler}}},");
            }
        }

        c.AppendLine("};").AppendLine("const int replay_table_count = (int)(sizeof replay_table / sizeof replay_table[0]);");
        return c.ToString().ReplaceLineEndings("\n");
    }

    private static string K(CKind e) => e.Name switch
    {
        "double" => "K_DOUBLE", "int32" or "enum" => "K_INT", "int64" => "K_LONG", "bool" => "K_BOOL", "date" => "K_DATE",
        "date?" => "K_OPTDATE", "period" => "K_PERIOD", "string" => "K_STR", "handle" => "K_OBJ", "complex" => "K_COMPLEX",
        "double?" => "K_OPTDOUBLE", "int32?" => "K_OPTINT",
        _ => throw new InvalidOperationException("no replay kind for " + e.Name),
    };

    private static void Handler(StringBuilder c, CFunction f, string h)
    {
        c.AppendLine($"static int {h}(rp* r, const jv* a, const jv* res, int t)").AppendLine("{");
        var args = new List<string>();
        var after = new List<string>();
        for (int j = 0; j < f.Params.Count; j++)
        {
            CKind k = f.Params[j].Kind;
            string p = "p" + j;
            switch (k.Name)
            {
                case "double": c.AppendLine($"    double {p} = rd_double(r, a, {j});"); args.Add(p); break;
                case "int32" or "enum": c.AppendLine($"    int32_t {p} = rd_int(r, a, {j});"); args.Add(p); break;
                case "int64": c.AppendLine($"    int64_t {p} = rd_long(r, a, {j});"); args.Add(p); break;
                case "bool": c.AppendLine($"    bool {p} = rd_bool(r, a, {j});"); args.Add(p); break;
                case "string": c.AppendLine($"    const char* {p} = rd_str(r, a, {j});"); args.Add(p); break;
                case "date" or "date?": c.AppendLine($"    nql_date {p} = rd_date(r, a, {j});"); args.Add(p); break;
                case "period": c.AppendLine($"    nql_period {p} = rd_period(r, a, {j});"); args.Add(p); break;
                case "complex": c.AppendLine($"    nql_complex {p} = rd_complex(r, a, {j});"); args.Add(p); break;
                case "double?": c.AppendLine($"    double s{j}; const double* {p} = rd_optdouble(r, a, {j}, &s{j});"); args.Add(p); break;
                case "int32?" or "enum?": c.AppendLine($"    int32_t s{j}; const int32_t* {p} = rd_optint(r, a, {j}, &s{j});"); args.Add(p); break;
                case "int64?": c.AppendLine($"    int64_t s{j}; const int64_t* {p} = rd_optlong(r, a, {j}, &s{j});"); args.Add(p); break;
                case "bool?": c.AppendLine($"    bool s{j}; const bool* {p} = rd_optbool(r, a, {j}, &s{j});"); args.Add(p); break;
                case "period?": c.AppendLine($"    nql_period s{j}; const nql_period* {p} = rd_optperiod(r, a, {j}, &s{j});"); args.Add(p); break;
                case "complex?": c.AppendLine($"    nql_complex s{j}; const nql_complex* {p} = rd_optcomplex(r, a, {j}, &s{j});"); args.Add(p); break;
                case "handle" or "boxed" or "boxed?" or "snapshot": c.AppendLine($"    nql_handle {p} = rd_obj(r, a, {j});"); args.Add(p); break;
                case "matrix":
                    c.AppendLine($"    int32_t {p}r, {p}c; const double* {p} = rd_matrix(r, a, {j}, &{p}r, &{p}c);");
                    args.AddRange([p, p + "r", p + "c"]);
                    break;
                case "vector":
                    c.AppendLine($"    int32_t {p}n; const double* {p} = (const double*)rd_array(r, a, {j}, K_DOUBLE, NULL, &{p}n);");
                    args.AddRange([p, p + "n"]);
                    break;
                case "vector&":
                    c.AppendLine($"    int32_t {p}n; double* {p} = (double*)rd_array(r, a, {j}, K_DOUBLE, NULL, &{p}n);");
                    args.AddRange([p, p + "n"]);
                    after.Add($"ck_span(r, {after.Count}, {p}, {p}n);");
                    break;
                case "matrix&":
                    c.AppendLine($"    int32_t {p}r, {p}c; double* {p} = (double*)rd_matrix(r, a, {j}, &{p}r, &{p}c);");
                    args.AddRange([p, p + "r", p + "c"]);
                    after.Add($"ck_span(r, {after.Count}, {p}, {p}r * {p}c);");
                    break;
                case "span":
                {
                    string ct = k.Element!.Name == "double" ? "double" : "int32_t";
                    c.AppendLine($"    int32_t {p}n; {ct}* {p} = ({ct}*)rd_span(r, a, {j}, {K(k.Element!)}, &{p}n);");
                    args.AddRange([p, p + "n"]);
                    after.Add(k.Element.Name == "double" ? $"ck_span(r, {after.Count}, {p}, {p}n);" : $"ck_span_ints(r, {after.Count}, {p}, {p}n);");
                    break;
                }

                case "array":
                {
                    string ct = CForms.Element(k.Element!).CType;
                    string ptr = k.Element!.Name == "string" ? "const char* const*" : "const " + ct + "*";
                    c.AppendLine($"    int32_t {p}n; const bool* {p}h; {ptr} {p} = ({ptr})rd_array(r, a, {j}, {K(k.Element)}, &{p}h, &{p}n);");
                    args.Add(p);
                    if (k.Element.Name is "double?" or "int32?")
                    {
                        args.Add(p + "h");
                    }

                    args.Add(p + "n");
                    break;
                }

                case "jagged":
                    c.AppendLine($"    int32_t {p}n, {p}rows; const int32_t* {p}l; const double* {p} = rd_jagged(r, a, {j}, &{p}n, &{p}l, &{p}rows);");
                    args.AddRange([p, p + "n", p + "l", p + "rows"]);
                    break;
                case "map":
                {
                    string kt = CForms.Element(k.Element!).CType, vt = CForms.Element(k.Value!).CType;
                    string kp = k.Element!.Name == "string" ? "const char* const*" : "const " + kt + "*";
                    string vp = k.Value!.Name == "string" ? "const char* const*" : "const " + vt + "*";
                    c.AppendLine($"    const void *{p}k, *{p}v; const bool* {p}h; int32_t {p}n; rd_map(r, a, {j}, {K(k.Element)}, {K(k.Value)}, &{p}k, &{p}v, &{p}h, &{p}n);");
                    args.AddRange([$"({kp}){p}k", $"({vp}){p}v"]);
                    if (k.Value.Name is "double?" or "int32?")
                    {
                        args.Add(p + "h");
                    }

                    args.Add(p + "n");
                    break;
                }

                default:
                    throw new InvalidOperationException($"{f.CName}: no replay reader for {k.Text}");
            }
        }

        c.AppendLine("    if (r_stop(r)) return 0;");
        var outs = new List<string>();
        var checks = new List<string>();
        if (f.Return != null)
        {
            Outs(f.Return, "o", "res", c, outs, checks, f.Kind == "draws" ? "p1" : null);
        }

        c.AppendLine($"    nql_status s_ = {f.CName}({string.Join(", ", args.Concat(outs))});");
        c.AppendLine("    if (st(r, s_, t))").AppendLine("    {");
        foreach (string check in checks.Concat(after))
        {
            c.AppendLine("        " + check);
        }

        c.AppendLine("    }").AppendLine("    return 1;").AppendLine("}").AppendLine();
    }

    // Declares a result's out locals, adds their addresses to the call, and its checks against res.
    private static void Outs(CKind k, string o, string res, StringBuilder c, List<string> outs, List<string> checks, string? count = null)
    {
        switch (k.Name)
        {
            case "double": c.AppendLine($"    double {o} = 0;"); outs.Add("&" + o); checks.Add($"ck_double(r, {res}, {o});"); return;
            case "int32" or "enum": c.AppendLine($"    int32_t {o} = 0;"); outs.Add("&" + o); checks.Add($"ck_int(r, {res}, {o});"); return;
            case "int64": c.AppendLine($"    int64_t {o} = 0;"); outs.Add("&" + o); checks.Add($"ck_int(r, {res}, {o});"); return;
            case "bool": c.AppendLine($"    bool {o} = 0;"); outs.Add("&" + o); checks.Add($"ck_bool(r, {res}, {o});"); return;
            case "string": c.AppendLine($"    char* {o} = NULL;"); outs.Add("&" + o); checks.Add($"ck_str(r, {res}, {o});"); return;
            case "date" or "date?": c.AppendLine($"    nql_date {o} = 0;"); outs.Add("&" + o); checks.Add($"ck_int(r, {res}, {o});"); return;
            case "period": c.AppendLine($"    nql_period {o} = {{0, 0}};"); outs.Add("&" + o); checks.Add($"ck_period(r, {res}, {o});"); return;
            case "complex": c.AppendLine($"    nql_complex {o} = {{0, 0}};"); outs.Add("&" + o); checks.Add($"ck_complex(r, {res}, {o});"); return;
            case "double?" or "int32?" or "int64?" or "bool?" or "period?" or "enum?" or "complex?":
            {
                CKind inner = k with { Name = k.Name.TrimEnd('?') };
                string ct = inner.Name switch { "double" => "double", "int64" => "int64_t", "bool" => "bool", "period" => "nql_period", "complex" => "nql_complex", _ => "int32_t" };
                string kind = inner.Name switch { "double" => "K_DOUBLE", "int64" => "K_LONG", "bool" => "K_BOOL", "period" => "K_PERIOD", "complex" => "K_COMPLEX", _ => "K_INT" };
                c.AppendLine($"    {ct} {o}; bool {o}h = 0; memset(&{o}, 0, sizeof {o});");
                outs.AddRange(["&" + o, "&" + o + "h"]);
                checks.Add($"ck_opt(r, {res}, {o}h, {kind}, &{o});");
                return;
            }

            case "handle" or "boxed" or "boxed?" or "snapshot": c.AppendLine($"    nql_handle {o} = NULL;"); outs.Add("&" + o); checks.Add($"ck_obj(r, {res}, {o});"); return;
            case "draws":
                c.AppendLine($"    double *{o}v = NULL, *{o}w = NULL; nql_handle {o}n = NULL;");
                outs.AddRange([$"&{o}v", $"&{o}w", $"&{o}n"]);
                checks.Add($"ck_array(r, jv_at({res}, 0), K_DOUBLE, {o}v, NULL, {count}); ck_array(r, jv_at({res}, 1), K_DOUBLE, {o}w, NULL, {count}); ck_obj(r, jv_at({res}, 2), {o}n);");
                return;
            case "sequences":
                c.AppendLine($"    double *{o}v = NULL, *{o}w = NULL; int32_t {o}d = 0; nql_handle {o}n = NULL;");
                outs.AddRange([$"&{o}v", $"&{o}w", $"&{o}d", $"&{o}n"]);
                checks.Add($"ck_array(r, jv_at({res}, 0), K_DOUBLE, {o}v, NULL, {count} * {o}d); ck_array(r, jv_at({res}, 1), K_DOUBLE, {o}w, NULL, {count}); ck_int(r, jv_at({res}, 2), {o}d); ck_obj(r, jv_at({res}, 3), {o}n);");
                return;
            case "matrix":
                c.AppendLine($"    double* {o} = NULL; int32_t {o}r = 0, {o}c = 0;");
                outs.AddRange(["&" + o, $"&{o}r", $"&{o}c"]);
                checks.Add($"ck_matrix(r, {res}, {o}, {o}r, {o}c);");
                return;
            case "vector":
                c.AppendLine($"    double* {o} = NULL; int32_t {o}n = 0;");
                outs.AddRange(["&" + o, $"&{o}n"]);
                checks.Add($"ck_array(r, {res}, K_DOUBLE, {o}, NULL, {o}n);");
                return;
            case "array":
            {
                CKind e = k.Element!;
                string ct = e.Name == "string" ? "char*" : CForms.Element(e).CType;
                c.AppendLine($"    {ct}* {o} = NULL; bool* {o}h = NULL; int32_t {o}n = 0;");
                outs.Add("&" + o);
                if (e.Name is "double?" or "int32?")
                {
                    outs.Add($"&{o}h");
                }

                outs.Add($"&{o}n");
                checks.Add($"ck_array(r, {res}, {K(e)}, (void*){o}, {o}h, {o}n);");
                return;
            }

            case "jagged":
                c.AppendLine($"    double* {o} = NULL; int32_t* {o}l = NULL; int32_t {o}rows = 0;");
                outs.AddRange(["&" + o, $"&{o}l", $"&{o}rows"]);
                checks.Add($"ck_jagged(r, {res}, {o}, {o}l, {o}rows);");
                return;
            case "map":
            {
                string kt = k.Element!.Name == "string" ? "char*" : CForms.Element(k.Element).CType;
                string vt = k.Value!.Name == "string" ? "char*" : CForms.Element(k.Value).CType;
                c.AppendLine($"    {kt}* {o}k = NULL; {vt}* {o}v = NULL; bool* {o}h = NULL; int32_t {o}n = 0;");
                outs.AddRange([$"&{o}k", $"&{o}v"]);
                if (k.Value.Name is "double?" or "int32?")
                {
                    outs.Add($"&{o}h");
                }

                outs.Add($"&{o}n");
                checks.Add($"ck_map(r, {res}, {K(k.Element)}, {K(k.Value)}, (void*){o}k, (void*){o}v, {o}h, {o}n);");
                return;
            }

            case "tuple":
                for (int i = 0; i < k.Items.Count; i++)
                {
                    Outs(k.Items[i], o + "_" + i, $"jv_at({res}, {i})", c, outs, checks);
                }

                return;
            case "distribution":
                c.AppendLine($"    double *{o}x = NULL, *{o}dx = NULL, *{o}d = NULL, *{o}c = NULL, *{o}e = NULL, *{o}a = NULL; int32_t {o}n = 0;");
                outs.AddRange([$"&{o}x", $"&{o}dx", $"&{o}d", $"&{o}c", $"&{o}e", $"&{o}a", $"&{o}n"]);
                checks.Add($"ck_distribution(r, {res}, {o}x, {o}dx, {o}d, {o}c, {o}e, {o}a, {o}n);");
                return;
        }

        throw new InvalidOperationException("no replay check for " + k.Text);
    }
}
