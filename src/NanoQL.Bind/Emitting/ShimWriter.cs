using System.Reflection;
using System.Text;
using NanoQL.Bind.Model;
using NanoQL.Bind.Reading;

namespace NanoQL.Bind.Emitting;

/// <summary>
/// Writes the C# export shims the native host compiles: one <c>[UnmanagedCallersOnly]</c> method per C function, which
/// converts its C arguments, calls the member, writes its result through the out-parameters and returns 0, or catches
/// the exception and returns its code; and the engine adapters that turn a bound engine into the delegate a member
/// takes. The shims are generated at build, never checked in.
/// </summary>
internal sealed class ShimWriter(Surface surface)
{
    private const int PerFile = 400;
    private const string Rt = "global::NanoQL.Native.Rt";

    /// <summary>Writes the shims into a folder, replacing what it held.</summary>
    /// <param name="dir">The folder.</param>
    public void Write(string dir)
    {
        Directory.CreateDirectory(dir);
        foreach (string old in Directory.EnumerateFiles(dir, "*.g.cs"))
        {
            File.Delete(old);
        }

        int file = 0;
        for (int at = 0; at < surface.Functions.Count; at += PerFile, file++)
        {
            var sb = Header($"Exports{file:D3}");
            for (int i = at; i < Math.Min(at + PerFile, surface.Functions.Count); i++)
            {
                Function(sb, surface.Functions[i], i);
            }

            sb.AppendLine("}");
            Emit(dir, $"Exports{file:D3}.g.cs", sb);
        }

        var adapters = Header("EngineAdapters");
        new AdapterWriter(surface, "global::NanoQL.Native.BoundEngine").Write(adapters);
        adapters.AppendLine("}");
        Emit(dir, "EngineAdapters.g.cs", adapters);

        var version = new StringBuilder();
        version.AppendLine("// <auto-generated/>").AppendLine("namespace NanoQL.Native;").AppendLine("internal static class GeneratedVersion").AppendLine("{")
            .AppendLine($"    public const string Text = \"{Versions.Text}\";").AppendLine($"    public const int Abi = {Versions.Abi};").AppendLine("}");
        Emit(dir, "GeneratedVersion.g.cs", version);
    }

    private static StringBuilder Header(string cls) => new StringBuilder()
        .AppendLine("// <auto-generated/>").AppendLine("#nullable disable").AppendLine("#pragma warning disable")
        .AppendLine("using System.Runtime.InteropServices;").AppendLine("namespace NanoQL.Native;")
        .AppendLine($"internal static unsafe class {cls}").AppendLine("{");

    private static void Emit(string dir, string name, StringBuilder sb) => File.WriteAllText(Path.Combine(dir, name), sb.ToString().ReplaceLineEndings("\n"));

    private void Function(StringBuilder sb, CFunction f, int index)
    {
        List<CSlot> slots = CForms.All(f);
        sb.AppendLine($"    [UnmanagedCallersOnly(EntryPoint = \"{f.CName}\")]");
        sb.AppendLine($"    public static int F{index}({string.Join(", ", slots.Select(s => $"{s.CsType} @{s.Name}"))})");
        sb.AppendLine("    {").AppendLine("        try").AppendLine("        {");
        switch (f.Kind)
        {
            case "draws":
                Draws(sb, f);
                break;
            case "bind":
            case "bindon":
                Bind(sb, f);
                break;
            default:
                Call(sb, f);
                break;
        }

        sb.AppendLine("            return 0;").AppendLine("        }");
        foreach ((string exception, int code) in f.DocumentedCodes)
        {
            sb.AppendLine($"        catch (global::{exception} e_) {{ return {Rt}.Fail(e_, {code}); }}");
        }

        sb.AppendLine($"        catch (global::System.Exception e_) {{ return {Rt}.Fail(e_); }}").AppendLine("    }");
    }

    private void Call(StringBuilder sb, CFunction f)
    {
        // A Matrix or Vector the member writes into: built in a local, copied back into the caller's after the call.
        CParam[] inOut = [.. f.Params.Where(p => p.Kind.Name is "vector&" or "matrix&")];
        foreach (CParam p in inOut)
        {
            string n = "@" + CForms.Ident(p.Name);
            sb.AppendLine(p.Kind.Name == "vector&"
                ? $"            var io_{CForms.Ident(p.Name)} = {Rt}.Vector({n}, {n}_count);"
                : $"            var io_{CForms.Ident(p.Name)} = {Rt}.Matrix({n}, {n}_rows, {n}_columns);");
        }

        var args = f.Params.Where(p => !p.IsSelf).Select(p => Arg(p, f)).ToList();
        foreach (int dropped in f.Dropped)
        {
            args.Insert(dropped, "null");
        }

        string self = f.Params.Count > 0 && f.Params[0].IsSelf ? Self(f.Params[0]) : string.Empty;
        string holder = CsNames.Of(f.Holder);
        string generic = f.TypeArguments.Count > 0 ? "<" + string.Join(", ", f.TypeArguments.Select(CsNames.Of)) + ">" : string.Empty;
        string name = f.Member?.Name ?? f.BaseName;
        string call;
        switch (f.Kind)
        {
            case "new" when f.Member == null:
                // A struct's implicit parameterless constructor.
                call = $"default({CsNames.Of(f.Type)})";
                break;
            case "new":
                var required = f.Type.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                    .Where(p => p.Has("System.Runtime.CompilerServices.RequiredMemberAttribute")).OrderBy(p => p.MetadataToken).ToList();
                int nCtor = ((ConstructorInfo)f.Member).GetParameters().Length;
                call = !((ConstructorInfo)f.Member).Has("System.Diagnostics.CodeAnalysis.SetsRequiredMembersAttribute") && required.Count > 0
                    ? $"new {CsNames.Of(f.Type)}({string.Join(", ", args.Take(nCtor))}) {{ {string.Join(", ", required.Select((r, i) => r.Name + " = " + args[nCtor + i]))} }}"
                    : $"new {CsNames.Of(f.Type)}({string.Join(", ", args)})";
                break;
            case "static":
                call = $"{holder}.{name}{generic}({string.Join(", ", args)})";
                break;
            case "operator":
                call = Operator(name, args, f);
                break;
            case "method":
                call = $"(({holder}){self}).{name}{generic}({string.Join(", ", args)})";
                break;
            case "get":
                call = f.Static ? $"{holder}.{name[4..]}" : $"(({holder}){self}).{name[4..]}";
                break;
            case "set":
                sb.AppendLine($"            {holder}.{name[4..]} = {args[0]};");
                return;
            case "indexer":
                call = $"(({holder}){self})[{string.Join(", ", args)}]";
                break;
            case "field":
                call = f.Static ? $"{holder}.{name}" : $"(({holder}){self}).{name}";
                break;
            case "with":
                call = $"({self}) with {{ {name} = {args[0]} }}";
                break;
            default:
                throw new InvalidOperationException(f.Kind);
        }

        if (f.Return == null)
        {
            sb.AppendLine($"            {call};");
        }
        else
        {
            Store(sb, f.Return, "(" + call + ")", "result", f.Kind == "new", "            ");
        }

        foreach (CParam p in inOut)
        {
            string n = "@" + CForms.Ident(p.Name);
            sb.AppendLine(p.Kind.Name == "vector&"
                ? $"            {Rt}.CopyBack(io_{CForms.Ident(p.Name)}, {n}, {n}_count);"
                : $"            {Rt}.CopyBack(io_{CForms.Ident(p.Name)}, {n}, {n}_rows, {n}_columns);");
        }
    }

    private static string Operator(string name, List<string> a, CFunction f)
    {
        string? binary = name switch
        {
            "op_Addition" => "+", "op_Subtraction" => "-", "op_Multiply" => "*", "op_Division" => "/", "op_Modulus" => "%",
            "op_Equality" => "==", "op_Inequality" => "!=", "op_LessThan" => "<", "op_GreaterThan" => ">",
            "op_LessThanOrEqual" => "<=", "op_GreaterThanOrEqual" => ">=", "op_BitwiseAnd" => "&", "op_BitwiseOr" => "|",
            "op_ExclusiveOr" => "^", "op_LeftShift" => "<<", "op_RightShift" => ">>", "op_UnsignedRightShift" => ">>>",
            _ => null,
        };
        if (binary != null)
        {
            return $"({a[0]}) {binary} ({a[1]})";
        }

        return name switch
        {
            "op_UnaryNegation" => $"-({a[0]})",
            "op_UnaryPlus" => $"+({a[0]})",
            "op_LogicalNot" => $"!({a[0]})",
            "op_OnesComplement" => $"~({a[0]})",
            "op_Increment" => $"{Rt}.Increment({a[0]})",
            "op_Decrement" => $"{Rt}.Decrement({a[0]})",
            "op_Implicit" or "op_Explicit" => $"({CsNames.Of(((MethodInfo)f.Member!).ReturnType)})({a[0]})",
            _ => throw new InvalidOperationException($"{f.CName}: no syntax for the operator {name}"),
        };
    }

    private string Self(CParam p) => p.Kind.Name switch
    {
        "date" => $"{Rt}.Date(@self)",
        "period" => "@self.ToPeriod()",
        "boxed" => $"{Rt}.Unbox<{CsNames.Of(p.Kind.Type)}>(@self, \"self\")",
        "handle" when p.Kind.Type.FullName == "NanoQL.Extensions.Conventions.ConventionSet" => $"{Rt}.SelfSet(@self)",
        "handle" => $"{Rt}.Self<{CsNames.Of(p.Kind.Type)}>(@self)",
        _ => throw new InvalidOperationException("self of kind " + p.Kind.Name),
    };

    // A parameter's C# value from its C arguments.
    private string Arg(CParam p, CFunction f)
    {
        string n = "@" + CForms.Ident(p.Name);
        CKind k = p.Kind;
        string cs = CsNames.Of(k.Type);
        string pn = "\"" + p.Name + "\"";
        switch (k.Name)
        {
            case "double" or "int32" or "int64": return n;
            case "bool": return $"{n} != 0";
            case "string": return $"{Rt}.Str({n})";
            case "date": return $"{Rt}.Date({n})";
            case "date?": return $"{Rt}.OptDate({n})";
            case "period": return $"{n}.ToPeriod()";
            case "enum": return $"({cs})({n})";
            case "complex": return $"{n}.ToComplex()";
            case "double?" or "int32?" or "int64?": return $"({n} == null ? ({cs})null : *{n})";
            case "bool?": return $"({n} == null ? (bool?)null : *{n} != 0)";
            case "period?": return $"({n} == null ? ({cs})null : {n}->ToPeriod())";
            case "enum?": return $"({n} == null ? ({cs})null : ({CsNames.Of(k.Type.NullableOf()!)})(*{n}))";
            case "complex?": return $"({n} == null ? ({cs})null : {n}->ToComplex())";
            case "handle": return $"{Rt}.Get<{cs}>({n}, {pn})";
            // NULL for an optional struct is its default, what C# passes for the omitted argument.
            case "boxed" when p.Optional: return $"({n} == 0 ? default({cs}) : {Rt}.Unbox<{cs}>({n}, {pn}))";
            case "boxed": return $"{Rt}.Unbox<{cs}>({n}, {pn})";
            case "boxed?": return $"({n} == 0 ? ({cs})null : {Rt}.Unbox<{CsNames.Of(k.Type.NullableOf()!)}>({n}, {pn}))";
            case "snapshot": return $"{Rt}.Generator<{cs}>({n}, {pn})";
            case "engine": return $"EngineAdapters.A{k.Engine!.Index}({Rt}.Get<global::NanoQL.Native.BoundEngine>({n}, {pn}), \"{f.CName}\")";
            case "matrix": return $"{Rt}.Matrix({n}, {n}_rows, {n}_columns)";
            case "vector": return $"{Rt}.Vector({n}, {n}_count)";
            case "vector&" or "matrix&": return "io_" + CForms.Ident(p.Name);
            case "span": return $"new global::System.Span<{CsNames.Of(k.Element!.Type)}>({n}, {n}_count)";
            case "tuple":
                return "(" + string.Join(", ", k.Items.Select((item, i) => Arg(new CParam(CForms.ItemParam(p.Name, k, i), item, false, null), f))) + ")";
            case "array" when k.Element!.Name == "tuple":
            {
                // The tuples from their elements' arrays in step.
                CKind tk = k.Element;
                var arrays = tk.Items.Select((item, i) =>
                {
                    string en = "@" + CForms.ItemParam(p.Name, tk, i, true);
                    return Elements(item, en, en + "_has_value", n + "_count", p.Name);
                });
                string zipped = $"{Rt}.Zip({string.Join(", ", arrays)}, \"{p.Name}\")";
                return Wrap(k.Type, CsNames.Of(tk.Type), zipped);
            }

            case "array":
                if (k.Type.IsConstructionOf("System.ReadOnlySpan`1") && k.Element!.Name is "double" or "int32" or "int64")
                {
                    return $"new global::System.ReadOnlySpan<{CsNames.Of(k.Element.Type)}>({n}, {n}_count)";
                }

                return Wrap(k.Type, CsNames.Of(k.Element!.Type), Elements(k.Element!, n, n + "_has_value", n + "_count", p.Name));
            case "jagged":
            {
                Type inner = k.Type.IsArray ? k.Type.GetElementType()! : k.Type.GetGenericArguments()[0];
                string rows = $"{Rt}.Jagged({n}, {n}_count, {n}_row_lengths, {n}_rows)";
                if (inner.IsConstructionOf("System.Collections.Immutable.ImmutableArray`1"))
                {
                    rows = $"global::System.Linq.Enumerable.ToArray(global::System.Linq.Enumerable.Select({rows}, r_ => {Rt}.Immutable(r_)))";
                }

                return Wrap(k.Type, CsNames.Of(inner), rows);
            }

            case "map":
            {
                string keys = Elements(k.Element!, n + "_keys", null, n + "_count", p.Name);
                string values = Elements(k.Value!, n + "_values", n + "_has_value", n + "_count", p.Name);
                string kc = CsNames.Of(k.Element!.Type), vc = CsNames.Of(k.Value!.Type);
                string def = k.Type.IsGenericType ? k.Type.GetGenericTypeDefinition().FullName! : string.Empty;
                string dict = $"{Rt}.Dictionary<{kc}, {vc}>({keys}, {values})";
                return def switch
                {
                    "System.Collections.Immutable.ImmutableDictionary`2" or "System.Collections.Immutable.IImmutableDictionary`2" => $"{Rt}.ImmutableDictionary({dict})",
                    "System.Collections.Immutable.ImmutableSortedDictionary`2" => $"{Rt}.ImmutableSortedDictionary({dict})",
                    "System.Collections.Frozen.FrozenDictionary`2" => $"{Rt}.FrozenDictionary({dict})",
                    "System.Collections.Generic.IReadOnlyDictionary`2" or "System.Collections.Generic.IDictionary`2" or "System.Collections.Generic.Dictionary`2" => dict,
                    _ => Wrap(k.Type, $"global::System.Collections.Generic.KeyValuePair<{kc}, {vc}>", $"{Rt}.Pairs<{kc}, {vc}>({keys}, {values})"),
                };
            }
        }

        throw new InvalidOperationException("no shim argument for the kind " + k.Text);
    }

    // An array of a collection's elements, from the C pointer, its has-value flags for nullables, and its count.
    private static string Elements(CKind e, string n, string? has, string count, string name)
    {
        string cs = CsNames.Of(e.Type);
        return e.Name switch
        {
            "double" or "int32" or "int64" => $"{Rt}.Copy<{cs}>({n}, {count})",
            "bool" => $"{Rt}.Bools({n}, {count})",
            "date" => $"{Rt}.Dates({n}, {count})",
            "date?" => $"{Rt}.OptDates({n}, {count})",
            "period" => $"{Rt}.Periods({n}, {count})",
            "enum" => $"{Rt}.Enums<{cs}>({n}, {count})",
            "string" => $"{Rt}.Strs({n}, {count})",
            "complex" => $"{Rt}.Complexes({n}, {count})",
            "handle" => $"{Rt}.Objects<{cs}>({n}, {count}, \"{name}\")",
            "double?" => $"{Rt}.OptDoubles({n}, {has}, {count})",
            "int32?" => $"{Rt}.OptInts({n}, {has}, {count})",
            _ => throw new InvalidOperationException("no element conversion for " + e.Name),
        };
    }

    // An array, as the collection type the member takes.
    private static string Wrap(Type collection, string element, string array)
    {
        if (collection.IsArray)
        {
            return array;
        }

        return collection.GetGenericTypeDefinition().FullName switch
        {
            "System.ReadOnlySpan`1" => $"new global::System.ReadOnlySpan<{element}>({array})",
            "System.Collections.Immutable.ImmutableArray`1" => $"{Rt}.Immutable<{element}>({array})",
            "System.Collections.Generic.List`1" => $"{Rt}.List<{element}>({array})",
            "System.Collections.Immutable.ImmutableSortedSet`1" => $"{Rt}.SortedSet<{element}>({array})",
            "System.Collections.Immutable.ImmutableHashSet`1" => $"{Rt}.HashSet<{element}>({array})",
            "System.Collections.Generic.IReadOnlySet`1" => $"{Rt}.ReadOnlySet<{element}>({array})",
            "System.Collections.Immutable.ImmutableList`1" or "System.Collections.Immutable.IImmutableList`1" => $"{Rt}.ImmutableList<{element}>({array})",
            _ => array,
        };
    }

    // Writes a result through its out-parameters.
    private void Store(StringBuilder sb, CKind k, string v, string r, bool fresh, string ind)
    {
        string o = "@" + r;
        switch (k.Name)
        {
            case "double" or "int32" or "int64" or "bool" or "string" or "date" or "period" or "enum" or "complex" or "handle" or "boxed":
                sb.AppendLine($"{ind}*{o} = {Conv(k, v)};");
                return;
            case "date?":
                sb.AppendLine($"{ind}{{ var v_ = {v}; *{o} = v_.HasValue ? v_.Value.SerialNumber : 0; }}");
                return;
            case "double?" or "int32?" or "int64?" or "bool?" or "period?" or "enum?" or "complex?":
            {
                CKind inner = k with { Name = k.Name.TrimEnd('?'), Type = k.Type.NullableOf()! };
                sb.AppendLine($"{ind}{{ var v_ = {v}; *{o}_has_value = v_.HasValue ? (byte)1 : (byte)0; *{o} = v_.HasValue ? {Conv(inner, "v_.Value")} : default; }}");
                return;
            }

            case "boxed?":
                sb.AppendLine($"{ind}{{ var v_ = {v}; *{o} = v_.HasValue ? {Rt}.New((object)v_.Value) : 0; }}");
                return;
            case "snapshot":
                sb.AppendLine(fresh ? $"{ind}*{o} = {Rt}.New(new global::NanoQL.Native.GeneratorSnapshot({v}));" : $"{ind}*{o} = {Rt}.NewSnapshot({v});");
                return;
            case "matrix":
                sb.AppendLine($"{ind}{Rt}.OutMatrix({v}, {o}, {o}_rows, {o}_columns);");
                return;
            case "vector":
                sb.AppendLine($"{ind}{Rt}.OutVector({v}, {o}, {o}_count);");
                return;
            case "distribution":
                sb.AppendLine($"{ind}{Rt}.OutDistribution({v}, {o}_x, {o}_dx, {o}_density, {o}_cumulative, {o}_excess, {o}_average, {o}_count);");
                return;
            case "array" when k.Element!.Name is "tuple" or "tuple?":
            {
                // An array per element, a null tuple's flag cleared and its elements zero.
                CKind te = k.Element;
                bool nullable = te.Name == "tuple?";
                sb.Append($"{ind}{{ var a_ = {ToArray(k.Type, v)}; ");
                for (int i = 0; i < te.Items.Count; i++)
                {
                    CKind e = te.Items[i];
                    sb.Append($"var p{i}_ = {(e.Name == "string" ? $"(byte**){Rt}.Alloc<nint>(a_.Length)" : $"{Rt}.Alloc<{CForms.Element(e).CsType}>(a_.Length)")}; ");
                }

                if (nullable)
                {
                    sb.Append($"var h_ = {Rt}.Alloc<byte>(a_.Length); ");
                }

                sb.Append("for (int i_ = 0; i_ < a_.Length; i_++) { ");
                if (nullable)
                {
                    sb.Append("if (!a_[i_].HasValue) { h_[i_] = 0; " + string.Concat(Enumerable.Range(0, te.Items.Count).Select(i => $"p{i}_[i_] = default; ")) + "continue; } h_[i_] = 1; var t_ = a_[i_].GetValueOrDefault(); ");
                }
                else
                {
                    sb.Append("var t_ = a_[i_]; ");
                }

                for (int i = 0; i < te.Items.Count; i++)
                {
                    sb.Append($"p{i}_[i_] = {Conv(te.Items[i], $"t_.Item{i + 1}")}; ");
                }

                sb.Append("} ");
                for (int i = 0; i < te.Items.Count; i++)
                {
                    sb.Append($"*{CForms.ItemResult(te, i, true)} = p{i}_; ");
                }

                sb.AppendLine((nullable ? "*has_value = h_; " : string.Empty) + "*count = a_.Length; }");
                return;
            }

            case "array":
            {
                CKind e = k.Element!;
                string alloc = e.Name == "string" ? $"(byte**){Rt}.Alloc<nint>(a_.Length)" : $"{Rt}.Alloc<{CForms.Element(e).CsType}>(a_.Length)";
                sb.Append($"{ind}{{ var a_ = {ToArray(k.Type, v)}; var p_ = {alloc}; ");
                if (e.Name is "double?" or "int32?")
                {
                    sb.Append($"var h_ = {Rt}.Alloc<byte>(a_.Length); for (int i_ = 0; i_ < a_.Length; i_++) {{ p_[i_] = a_[i_].GetValueOrDefault(); h_[i_] = a_[i_].HasValue ? (byte)1 : (byte)0; }} *{o}_has_value = h_; ");
                }
                else
                {
                    sb.Append($"for (int i_ = 0; i_ < a_.Length; i_++) {{ p_[i_] = {Conv(e, "a_[i_]")}; }} ");
                }

                sb.AppendLine($"*{o} = p_; *{o}_count = a_.Length; }}");
                return;
            }

            case "jagged":
                sb.AppendLine($"{ind}{Rt}.OutJagged(global::System.Linq.Enumerable.ToArray(global::System.Linq.Enumerable.Select({ToArray(k.Type, v)}, row_ => global::System.Linq.Enumerable.ToArray(row_))), {o}, {o}_row_lengths, {o}_rows);");
                return;
            case "map":
            {
                CKind kk = k.Element!, vk = k.Value!;
                string allocK = kk.Name == "string" ? $"(byte**){Rt}.Alloc<nint>(a_.Length)" : $"{Rt}.Alloc<{CForms.Element(kk).CsType}>(a_.Length)";
                string allocV = vk.Name == "string" ? $"(byte**){Rt}.Alloc<nint>(a_.Length)" : $"{Rt}.Alloc<{CForms.Element(vk).CsType}>(a_.Length)";
                sb.Append($"{ind}{{ var a_ = global::System.Linq.Enumerable.ToArray({v}); var k_ = {allocK}; var w_ = {allocV}; ");
                if (vk.Name is "double?" or "int32?")
                {
                    sb.Append($"var h_ = {Rt}.Alloc<byte>(a_.Length); for (int i_ = 0; i_ < a_.Length; i_++) {{ k_[i_] = {Conv(kk, "a_[i_].Key")}; w_[i_] = a_[i_].Value.GetValueOrDefault(); h_[i_] = a_[i_].Value.HasValue ? (byte)1 : (byte)0; }} *{o}_has_value = h_; ");
                }
                else
                {
                    sb.Append($"for (int i_ = 0; i_ < a_.Length; i_++) {{ k_[i_] = {Conv(kk, "a_[i_].Key")}; w_[i_] = {Conv(vk, "a_[i_].Value")}; }} ");
                }

                sb.AppendLine($"*{o}_keys = k_; *{o}_values = w_; *{o}_count = a_.Length; }}");
                return;
            }

            case "tuple":
                sb.AppendLine($"{ind}{{").AppendLine($"{ind}    var t_ = {v};");
                for (int i = 0; i < k.Items.Count; i++)
                {
                    Store(sb, k.Items[i], $"t_.Item{i + 1}", OutName(k, i), false, ind + "    ");
                }

                sb.AppendLine($"{ind}}}");
                return;
        }

        throw new InvalidOperationException("no shim result for the kind " + k.Text);
    }

    // A tuple element's out name, as CForms.Out names it.
    private static string OutName(CKind tuple, int i) => CForms.ItemResult(tuple, i);

    private static string ToArray(Type collection, string v) =>
        collection.IsArray ? v
        : collection.IsConstructionOf("System.ReadOnlySpan`1") || collection.IsConstructionOf("System.Span`1") ? $"({v}).ToArray()"
        : $"global::System.Linq.Enumerable.ToArray({v})";

    // A scalar's or an element's C value.
    private static string Conv(CKind e, string x) => e.Name switch
    {
        "double" or "int32" or "int64" => x,
        "bool" => $"(({x}) ? (byte)1 : (byte)0)",
        "string" => $"{Rt}.NewStr({x})",
        "date" => $"({x}).SerialNumber",
        "date?" => $"(({x}).HasValue ? ({x}).Value.SerialNumber : 0)",
        "period" => $"new global::NanoQL.Native.NqlPeriod({x})",
        "enum" => $"(int)({x})",
        "complex" => $"new global::NanoQL.Native.NqlComplex({x})",
        "handle" => $"{Rt}.New({x})",
        "boxed" => $"{Rt}.New((object)({x}))",
        _ => throw new InvalidOperationException("no C value for " + e.Name),
    };

    private void Draws(StringBuilder sb, CFunction f)
    {
        bool sequences = f.Return!.Name == "sequences";
        string iface = sequences ? "global::NanoQL.Numerics.IRsg" : "global::NanoQL.Numerics.IRng";
        sb.AppendLine("            global::System.ArgumentOutOfRangeException.ThrowIfNegative(@count, \"count\");");
        sb.AppendLine($"            var g_ = ({iface})(({iface}){Rt}.SnapshotOf<{CsNames.Of(f.Type)}>(@self)).Clone();");
        if (sequences)
        {
            sb.AppendLine("            int d_ = g_.Dimension;");
            sb.AppendLine($"            var v_ = {Rt}.Alloc<double>(checked(@count * d_));");
            sb.AppendLine($"            var w_ = {Rt}.Alloc<double>(@count);");
            sb.AppendLine("            for (int i_ = 0; i_ < @count; i_++) { var s_ = g_.NextSequence(); s_.Value.Span.CopyTo(new global::System.Span<double>(v_ + ((long)i_ * d_), d_)); w_[i_] = s_.Weight; }");
            sb.AppendLine("            *@values = v_; *@weights = w_; *@dimension = d_;");
        }
        else
        {
            sb.AppendLine($"            var v_ = {Rt}.Alloc<double>(@count);");
            sb.AppendLine($"            var w_ = {Rt}.Alloc<double>(@count);");
            sb.AppendLine("            for (int i_ = 0; i_ < @count; i_++) { var s_ = g_.Next(); v_[i_] = s_.Value; w_[i_] = s_.Weight; }");
            sb.AppendLine("            *@values = v_; *@weights = w_;");
        }

        sb.AppendLine($"            *@next = {Rt}.New(new global::NanoQL.Native.GeneratorSnapshot(g_));");
    }

    private void Bind(StringBuilder sb, CFunction f)
    {
        EngineInputSet set = f.InputSet!;
        sb.AppendLine("            var d_ = new global::System.Collections.Generic.Dictionary<string, object>(global::System.StringComparer.Ordinal);");
        string instrument = "null";
        foreach (CParam p in f.Params)
        {
            if (p.Name == "instrument" && f.Kind == "bindon" && p == f.Params[0])
            {
                instrument = $"{Rt}.Required<{CsNames.Of(p.Kind.Type)}>(@instrument, \"instrument\")";
                continue;
            }

            ParameterInfo input = set.Inputs.Single(i => i.Name == p.Name);
            string n = "@" + CForms.Ident(p.Name);
            string given = p.Kind.Name is "handle" or "boxed?" or "snapshot" ? $"{n} != 0" : p.Kind.Name is "date" or "date?" ? $"{n} != 0" : $"{n} != null";
            if (p.Kind.Name == "array" && p.Kind.Element?.Name == "tuple")
            {
                // A collection of tuples is open when its first element's array is NULL.
                given = $"@{CForms.ItemParam(p.Name, p.Kind.Element, 0, true)} != null";
            }
            string value = p.Kind.Name switch
            {
                "double?" or "int32?" or "int64?" => $"*{n}",
                "bool?" => $"*{n} != 0",
                "period?" => $"{n}->ToPeriod()",
                "enum?" => $"({CsNames.Of(p.Kind.Type.NullableOf() ?? p.Kind.Type)})(*{n})",
                "complex?" => $"{n}->ToComplex()",
                "boxed?" => $"{Rt}.Unbox<{CsNames.Of(p.Kind.Type.NullableOf() ?? p.Kind.Type)}>({n}, \"{p.Name}\")",
                "date" or "date?" => $"{Rt}.Date({n})",
                _ => Arg(p, f),
            };
            string stored = AdapterWriter.Stored(input.ParameterType);
            if (stored != CsNames.Of(input.ParameterType))
            {
                value = $"({value}).ToArray()";
            }

            sb.AppendLine($"            if ({given}) d_[\"{p.Name}\"] = ({stored})({value});");
        }

        sb.AppendLine($"            *@result = {Rt}.New(new global::NanoQL.Native.BoundEngine(\"{set.Id}\", {instrument}, d_));");
    }
