using System.Globalization;
using System.Text;
using NanoQL.Bind.Model;
using NanoQL.Bind.Reading;
using NanoQL.Bind.Selecting;

namespace NanoQL.Bind.Emitting;

/// <summary>
/// Writes <c>coverage.md</c>: the surface's counts, every member that doesn't cross with its reason, the withheld
/// presets and their lookups, and every bound-engine pair: where each supplied argument goes, the pairs refused at the
/// call, and each calculation for a member's instrument that forms no pair, with why.
/// </summary>
internal static class CoverageWriter
{
    /// <summary>The report's text.</summary>
    /// <param name="surface">The surface.</param>
    /// <returns>The markdown, LF line endings.</returns>
    public static string Write(Surface surface)
    {
        var sb = new StringBuilder();
        string N(int n) => n.ToString("N0", CultureInfo.InvariantCulture);
        sb.AppendLine("<!-- SPDX-FileCopyrightText: 2026 The nanoql Authors").AppendLine("     SPDX-License-Identifier: Apache-2.0 -->").AppendLine();
        sb.AppendLine("# The C surface's coverage").AppendLine();
        sb.AppendLine("Generated by `nanoql-bind` with `nanoql.h` and `surface.json`; do not edit. docs/bindings.md gives the rules this");
        sb.AppendLine("report applies.").AppendLine();
        sb.AppendLine("## Counts").AppendLine();
        sb.AppendLine($"- **Assemblies:** {string.Join(", ", surface.Assemblies.Select(a => $"`{a.Assembly}` (`{a.Prefix}_`)"))}.");
        sb.AppendLine($"- **Functions:** {N(surface.Functions.Count)}, {N(surface.Functions.Count(f => f.Experimental))} of them experimental and "
            + $"{N(surface.Functions.Count(f => f.Overloaded))} with an overload suffix; by kind, "
            + string.Join(", ", surface.Functions.GroupBy(f => f.Kind).OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal).Select(g => $"{g.Key} {N(g.Count())}")) + ".");
        sb.AppendLine($"- **Types:** {N(surface.Types.Count)}; by form, "
            + string.Join(", ", surface.Types.GroupBy(t => t.Form).OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal).Select(g => $"{g.Key} {N(g.Count())}")) + ".");
        sb.AppendLine($"- **Enums:** {N(surface.Enums.Count)}.");
        sb.AppendLine($"- **Names:** the longest {surface.Functions.Max(f => f.CName.Length)} characters, {N(surface.Functions.Count(f => f.CName.Length > 63))} over 63.");
        sb.AppendLine($"- **Presets withheld:** {N(surface.Presets.Select(p => p.Construction.Constructor).Distinct().Count())} constructors of "
            + $"{N(surface.Presets.Select(p => p.Factory.PresetType).Distinct().Count())} types, {N(surface.Presets.Count(p => p.Lookup != null))} of the "
            + $"{N(surface.Presets.Count)} preset constructions with a lookup by name.");
        sb.AppendLine($"- **Engines:** {N(surface.EngineSets.Select(s => s.Engine).Distinct().Count())} engines, {N(surface.EngineSets.Count)} input sets; "
            + $"{N(surface.EngineParameters.Count)} engine parameters, {N(surface.EnginePairs.Count(p => p.Formed))} pairs formed, "
            + $"{N(surface.EnginePairs.Count(p => p.Refused))} refused at the call, {N(surface.EnginePairs.Count(p => !p.Formed && !p.Refused))} calculations forming no pair.");
        sb.AppendLine($"- **Not crossing:** {N(surface.Skips.Count)} members and types.").AppendLine();

        sb.AppendLine("## What doesn't cross, by reason").AppendLine();
        foreach (IGrouping<string, SkipRow> g in surface.Skips.GroupBy(s => Reason(s.Reason)).OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal))
        {
            sb.AppendLine($"### {g.Key} ({N(g.Count())})").AppendLine();
            foreach (SkipRow s in g.OrderBy(s => s.Display, StringComparer.Ordinal).ThenBy(s => s.Key, StringComparer.Ordinal))
            {
                sb.AppendLine($"- `{s.Display}`" + (s.Reason != g.Key ? ": " + s.Reason : string.Empty) + $" <sub>`{s.Key}`</sub>");
            }

            sb.AppendLine();
        }

        sb.AppendLine("## Presets by name").AppendLine();
        sb.AppendLine("Each coded preset's constructor is withheld; the convention set's lookup gives the same preset by its name. The recorder");
        sb.AppendLine("writes a constructor call whose arguments match a preset's as that lookup.").AppendLine();
        foreach (PresetRow p in surface.Presets.OrderBy(p => p.Factory.Dictionary, StringComparer.Ordinal).ThenBy(p => p.Factory.Name, StringComparer.Ordinal))
        {
            sb.AppendLine($"- `{p.Factory.Dictionary}[\"{p.Factory.Name}\"]`: `{TypeNamer.Simple(p.Factory.PresetType)}`, " + (p.Lookup != null ? $"`{p.Lookup.CName}`" : "no lookup takes the lambda's parameters it passes"));
        }

        sb.AppendLine().AppendLine("## Matrix and Vector arguments their members write").AppendLine();
        sb.AppendLine("Found from IL: the member, an override or an implementation changes the argument, or passes it to a member that does.");
        sb.AppendLine("Each crosses in and out (`vector&`, `matrix&`): `double*` with its counts, written back after the call.").AppendLine();
        foreach ((CFunction f, CParam w) in surface.Written.OrderBy(x => x.Function.CName, StringComparer.Ordinal).ThenBy(x => x.Parameter.Name, StringComparer.Ordinal))
        {
            sb.AppendLine($"- `{f.CName}`: `{w.Name}`" + (f.Experimental ? " (experimental)" : string.Empty));
        }

        if (surface.WrittenElsewhere.Count > 0)
        {
            sb.AppendLine().AppendLine("Written only by another assembly's override, where the member itself reads: the function crosses as the member's");
            sb.AppendLine("own form has it, and the override's write doesn't reach the caller through it.").AppendLine();
            foreach ((CFunction f, CParam w, string prefix) in surface.WrittenElsewhere.OrderBy(x => x.Function.CName, StringComparer.Ordinal).ThenBy(x => x.Parameter.Name, StringComparer.Ordinal))
            {
                sb.AppendLine($"- `{f.CName}`: `{w.Name}`, by an override in `{prefix}`'s assembly");
            }
        }

        sb.AppendLine().AppendLine("## Bound engines").AppendLine();
        sb.AppendLine("### The roles table").AppendLine();
        foreach ((string member, int argument, string[] parameters) in surface.Roles)
        {
            sb.AppendLine($"- `{member}`, argument {argument}: `{string.Join("`, `", parameters)}`");
        }

        foreach (IGrouping<CFunction, EnginePair> m in surface.EnginePairs.GroupBy(p => p.Member).OrderBy(g => g.Key.CName, StringComparer.Ordinal))
        {
            sb.AppendLine().AppendLine($"### `{m.Key.CName}`").AppendLine();
            foreach (EnginePair p in m.OrderBy(p => p.Set.Id, StringComparer.Ordinal))
            {
                string calc = p.Calculation is { } c ? $"`{TypeNamer.Simple(c.DeclaringType!)}.Calculate({string.Join(", ", c.GetParameters().Select(x => Describe.Type(x.ParameterType)))})`" : $"`{p.Set.Id}`";
                string what = p.Formed
                    ? (p.How.Count > 0 ? string.Join("; ", p.How) : p.Parameter.Instrument == null ? "the instrument bound by BindOn" : "no supplied argument")
                    : p.Refused ? "refused at the call: " + p.Reason : "no pair: " + p.Reason;
                sb.AppendLine($"- {calc}: {what}");
            }
        }

        return sb.ToString().ReplaceLineEndings("\n");
    }

    // A reason's group: a type's name after the colon groups with its kind.
    private static string Reason(string reason)
    {
        foreach (string head in new[] { "return: ", "takes or returns a working type: ", "BCL struct ", "BCL class ", "collection of ", "nullable of ", "dictionary of ", "tuple element: ", "immutable collection ", "overload with the same C signature as another: " })
        {
            if (reason.StartsWith(head, StringComparison.Ordinal))
            {
                return head == "return: " ? "return: " + Reason(reason[head.Length..]) : head.TrimEnd(' ', ':');
            }
        }

        return reason;
    }
}
