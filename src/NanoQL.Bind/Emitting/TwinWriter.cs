using System.Reflection;
using System.Text;
using System.Text.Json;
using NanoQL.Bind.Model;
using NanoQL.Bind.Reading;

namespace NanoQL.Bind.Emitting;

/// <summary>
/// Writes the recorder's twins (docs/bindings.md, "The vector suite through each binding"): for each function a C#
/// method with its member's managed signature that calls the member and writes the call as its C function's, its
/// arguments and result in the C ABI's forms; a preset's constructor written as its set's lookup by name; and a
/// generator's draws written as <c>Draws</c> calls along its snapshots. The recorder (tools/replay) compiles them and
/// rewrites the test assembly's call sites into them; <c>twins.json</c> maps each member key to its twin.
/// </summary>
internal sealed class TwinWriter(Surface surface)
{
    private const string Rec = "global::NanoQL.Replay.Rec";

    /// <summary>Writes <c>Twins.g.cs</c> and <c>twins.json</c> into a folder.</summary>
    /// <param name="dir">The folder.</param>
    public void Write(string dir)
    {
        Directory.CreateDirectory(dir);
        var cs = new StringBuilder()
            .AppendLine("// <auto-generated/>").AppendLine("#nullable disable").AppendLine("#pragma warning disable")
            .AppendLine("namespace NanoQL.Replay;").AppendLine("public static class Twins").AppendLine("{");
        var map = new List<(string Key, string Twin, string Site)>();
        int index = 0;

        // A member a named class surfaces from its closed generic base is one member key for each class's function:
        // its twin writes the function of the receiver's own class.
        var byKey = surface.Functions.Where(f => f.Member is MethodBase).GroupBy(f => FunctionKey(f, (MethodBase)f.Member!)).ToDictionary(g => g.Key, g => g.ToList());
        var done = new HashSet<string>(StringComparer.Ordinal);
        foreach (CFunction f in surface.Functions)
        {
            // A constructor whose C function takes its type's required members too has no call site of its own shape:
            // C# callers set them in an object initializer.
            if (f.Kind is "new" or "method" or "static" or "get" or "indexer" or "operator" or "set" && f.Member is MethodBase m
                && f.Params.Count(p => !p.IsSelf) + (f.DroppedParameter >= 0 ? 1 : 0) == m.GetParameters().Length)
            {
                string key = FunctionKey(f, m);
                if (!done.Add(key))
                {
                    continue;
                }

                string twin = "F" + index++;
                Twin(cs, f, m, twin, Receivers(f, m, byKey[key]));
                map.Add((key, twin, Site(f, m)));
            }
        }

        var presets = new List<(System.Reflection.ConstructorInfo Ctor, string Twin)>();
        foreach (IGrouping<System.Reflection.ConstructorInfo, PresetRow> ctor in surface.Presets.Where(p => p.Lookup != null).GroupBy(p => p.Construction.Constructor))
        {
            string twin = "P" + index++;
            Preset(cs, ctor.Key, [.. ctor], twin);
            map.Add((ctor.Key.MemberKey(), twin, "newobj"));
            presets.Add((ctor.Key, twin));
        }

        Reflection(cs, map, presets);
        Records(cs, map, ref index);
        Generators(cs, map, ref index);

        // A struct made by default or new T(), which has no call site, is written as its implicit constructor's call (R16).
        cs.AppendLine("    public static string DefaultNew(global::System.Type t) => t.FullName switch").AppendLine("    {");
        foreach (CFunction f in surface.Functions.Where(f => f.Kind == "new" && f.Member == null).OrderBy(f => f.Type.FullName, StringComparer.Ordinal))
        {
            cs.AppendLine($"        \"{f.Type.FullName}\" => \"{f.CName}\",");
        }

        cs.AppendLine("        _ => null,").AppendLine("    };");
        cs.AppendLine("}");
        File.WriteAllText(Path.Combine(dir, "Twins.g.cs"), cs.ToString().ReplaceLineEndings("\n"));
        WriteMap(Path.Combine(dir, "twins.json"), map);
    }

    /// <summary>Writes <c>twins.json</c>: each member key's twin and call site.</summary>
    /// <param name="path">The file.</param>
    /// <param name="map">The member keys, their twins and their sites.</param>
    internal static void WriteMap(string path, IEnumerable<(string Key, string Twin, string Site)> map)
    {
        // The writer doesn't close the stream it's given: the file is closed here, before the caller reads it back.
        using FileStream file = File.Create(path);
        using var json = new Utf8JsonWriter(file, new JsonWriterOptions { Indented = true });
        json.WriteStartObject();
        foreach ((string key, string twin, string site) in map)
        {
            json.WriteStartArray(key);
            json.WriteStringValue(twin);
            json.WriteStringValue(site);
            json.WriteEndArray();
        }

        json.WriteEndObject();
    }

    // The functions a call site's receiver may name: those sharing the member's key, and for a member a closed generic
    // base declares, every crossing class's function of that name and C signature deriving from the base, since a
    // class that overrides the member names its own.
    private List<CFunction> Receivers(CFunction f, MethodBase m, List<CFunction> shared)
    {
        if (m.IsStatic || f.Holder == f.Type || !f.Holder.IsConstructedGenericType)
        {
            return shared;
        }

        string sig = string.Join(",", f.Params.Where(p => !p.IsSelf).Select(p => p.Kind.Text));
        return
        [
            .. shared.Concat(surface.Functions.Where(g => g.BaseName == f.BaseName && g.Kind == f.Kind && !g.Static && g.Type != f.Type
                && f.Holder.IsAssignableFrom(g.Type) && string.Join(",", g.Params.Where(p => !p.IsSelf).Select(p => p.Kind.Text)) == sig)).Distinct(),
        ];
    }

    private static string FunctionKey(CFunction f, MethodBase m) =>
        m.MemberKey() + (f.TypeArguments.Count > 0 ? "<" + string.Join(",", f.TypeArguments.Select(a => a.KeyName())) + ">" : string.Empty);

    // How call sites reach the member: newobj for a constructor, a static call, or an instance call whose receiver a
    // value type passes by reference.
    private static string Site(CFunction f, MethodBase m) =>
        f.Kind == "new" ? "newobj" : m.IsStatic ? "static" : m.DeclaringType!.IsValueType ? "byref" : "instance";

    private void Twin(StringBuilder cs, CFunction f, MethodBase m, string twin, List<CFunction> shared)
    {
        ParameterInfo[] ps = m.GetParameters();
        var sig = new List<string>();
        if (f.Kind != "new" && !m.IsStatic)
        {
            sig.Add((m.DeclaringType!.IsValueType ? "ref " : string.Empty) + CsNames.Of(m.DeclaringType!) + " self");
        }

        sig.AddRange(ps.Select((p, i) => CsNames.Of(p.ParameterType) + " a" + i));
        Type ret = f.Kind == "new" ? m.DeclaringType! : ((MethodInfo)m).ReturnType;
        string retCs = ret.FullName == "System.Void" ? "void" : CsNames.Of(ret);
        string generic = f.TypeArguments.Count > 0 ? "<" + string.Join(", ", f.TypeArguments.Select(CsNames.Of)) + ">" : string.Empty;
        string holder = CsNames.Of(m.DeclaringType!);
        var args = ps.Select((_, i) => "a" + i).ToList();
        string call = f.Kind switch
        {
            "new" => $"new {holder}({string.Join(", ", args)})",
            "static" => $"{holder}.{m.Name}{generic}({string.Join(", ", args)})",
            "method" => $"self.{m.Name}{generic}({string.Join(", ", args)})",
            "get" => m.IsStatic ? $"{holder}.{m.Name[4..]}" : $"self.{m.Name[4..]}",
            "indexer" => $"self[{string.Join(", ", args)}]",
            "set" => $"{holder}.{m.Name[4..]} = a0",
            "operator" => Operator(m, args),
            _ => throw new InvalidOperationException(f.Kind),
        };

        cs.AppendLine($"    public static {retCs} {twin}({string.Join(", ", sig)})").AppendLine("    {");
        bool returns = retCs != "void";
        cs.AppendLine(returns ? $"        if (!{Rec}.On) return {call};" : $"        if (!{Rec}.On) {{ {call}; return; }}");
        string name = $"\"{f.CName}\"";
        if (shared.Count > 1 && !m.IsStatic)
        {
            // The receiver's own class names the function; an object of another class isn't written.
            name = "fn_";
            cs.Append("        string fn_ = ");
            foreach (CFunction s in shared.OrderByDescending(s => Depth(s.Type)))
            {
                cs.Append($"self is {CsNames.Of(s.Type)} ? \"{s.CName}\" : ");
            }

            cs.AppendLine("null;");
            cs.AppendLine(returns ? $"        if (fn_ == null) return {call};" : $"        if (fn_ == null) {{ {call}; return; }}");
        }

        // A capture that throws spoils its own line, never the call.
        cs.AppendLine($"        var w_ = {Rec}.Args();");
        cs.AppendLine("        try");
        cs.AppendLine("        {");
        int at = 0;
        foreach (CParam p in f.Params)
        {
            if (p.IsSelf)
            {
                cs.AppendLine($"            {Capture(p.Kind, "self")};");
                continue;
            }

            if (at == f.DroppedParameter)
            {
                at++;
            }

            cs.AppendLine($"            {Capture(p.Kind, "a" + at)};");
            at++;
        }

        cs.AppendLine("        }");
        cs.AppendLine("        catch (global::System.Exception) { w_.Spoil(); }");

        // A Matrix or Vector argument crosses in only: its contents before the call, to check after it that the member
        // didn't write into it, which the C call wouldn't give back (B1-1).
        CParam[] arrays = [.. f.Params.Where(p => !p.IsSelf && p.Kind.Name is "matrix" or "vector")];
        foreach (CParam a in arrays)
        {
            cs.AppendLine($"        double[] before_{ParamName(f, a)} = {Rec}.Contents({ParamName(f, a)});");
        }

        cs.AppendLine($"        {Rec}.Enter();");
        cs.AppendLine(returns ? $"        {retCs} r_;" : string.Empty);
        cs.AppendLine($"        try {{ {(returns ? "r_ = " : string.Empty)}{call}; }}");
        cs.AppendLine($"        catch (global::System.Exception e_) {{ {Rec}.Leave(); {Rec}.Throws({name}, w_, e_); throw; }}");
        cs.AppendLine($"        {Rec}.Leave();");
        cs.AppendLine("        try");
        cs.AppendLine("        {");
        cs.AppendLine("            w_.Result();");
        if (f.Return != null)
        {
            cs.AppendLine($"            {Result(f.Return, "r_", f.Kind == "new")};");
        }
        else
        {
            cs.AppendLine("            w_.Void();");
        }

        // A writable span's values after the call, and an in-out Matrix's or Vector's (R15), each in order.
        CParam[] spans = [.. f.Params.Where(p => p.Kind.Name is "span" or "vector&" or "matrix&")];
        if (spans.Length > 0)
        {
            cs.AppendLine("            w_.BeginAfter();");
            foreach (CParam s in spans)
            {
                cs.AppendLine(s.Kind.Name == "span"
                    ? $"            w_.{(s.Kind.Element!.Name == "double" ? "Doubles" : "Ints")}({ParamName(f, s)});"
                    : $"            w_.Doubles({Rec}.Contents({ParamName(f, s)}));");
            }

            cs.AppendLine("            w_.EndAfter();");
        }

        foreach (CParam a in arrays)
        {
            cs.AppendLine($"            if (!{Rec}.SameContents({ParamName(f, a)}, before_{ParamName(f, a)})) w_.Spoil();");
        }

        cs.AppendLine("        }");
        cs.AppendLine("        catch (global::System.Exception) { w_.Spoil(); }");
        cs.AppendLine($"        {Rec}.Call({name}, w_);");

        // A member that takes a generator gets a private copy through the C ABI, where C# hands it the generator
        // itself, which it may draw from: after the call the trace can't follow that generator.
        foreach (CParam s in f.Params.Where(p => p.Kind.Name == "snapshot" && !p.IsSelf))
        {
            cs.AppendLine($"        {Rec}.Forget({ParamName(f, s)});");
        }
        if (returns)
        {
            cs.AppendLine("        return r_;");
        }

        cs.AppendLine("    }");
    }

    private static string ParamName(CFunction f, CParam p)
    {
        int at = 0;
        foreach (CParam q in f.Params.Where(q => !q.IsSelf))
        {
            if (at == f.DroppedParameter)
            {
                at++;
            }

            if (q == p)
            {
                return "a" + at;
            }

            at++;
        }

        throw new InvalidOperationException(p.Name);
    }

    private static string Operator(MethodBase m, List<string> a) => m.Name switch
    {
        "op_Addition" => $"{a[0]} + {a[1]}", "op_Subtraction" => $"{a[0]} - {a[1]}", "op_Multiply" => $"{a[0]} * {a[1]}",
        "op_Division" => $"{a[0]} / {a[1]}", "op_Modulus" => $"{a[0]} % {a[1]}", "op_Equality" => $"{a[0]} == {a[1]}",
        "op_Inequality" => $"{a[0]} != {a[1]}", "op_LessThan" => $"{a[0]} < {a[1]}", "op_GreaterThan" => $"{a[0]} > {a[1]}",
        "op_LessThanOrEqual" => $"{a[0]} <= {a[1]}", "op_GreaterThanOrEqual" => $"{a[0]} >= {a[1]}",
        "op_BitwiseAnd" => $"{a[0]} & {a[1]}", "op_BitwiseOr" => $"{a[0]} | {a[1]}", "op_ExclusiveOr" => $"{a[0]} ^ {a[1]}",
        "op_UnaryNegation" => $"-{a[0]}", "op_UnaryPlus" => $"+{a[0]}", "op_LogicalNot" => $"!{a[0]}", "op_OnesComplement" => $"~{a[0]}",
        "op_Increment" => $"global::NanoQL.Replay.Rec.Increment({a[0]})", "op_Decrement" => $"global::NanoQL.Replay.Rec.Decrement({a[0]})",
        "op_Implicit" or "op_Explicit" => $"({CsNames.Of(((MethodInfo)m).ReturnType)})({a[0]})",
        _ => throw new InvalidOperationException("no syntax for the operator " + m.Name),
    };

    // An argument written in its C form, before the call: objects by their ids.
    private static string Capture(CKind k, string x) => k.Name switch
    {
        "double" => $"w_.Double({x})",
        "int32" or "enum" => $"w_.Int((int)({x}))",
        "int64" => $"w_.Long({x})",
        "bool" => $"w_.Bool({x})",
        "string" => $"w_.Str({x})",
        "date" => $"w_.Date({x})",
        "date?" => $"w_.OptDate({x})",
        "period" => $"w_.Period({x})",
        "period?" => $"w_.OptPeriod({x})",
        "complex" => $"w_.Complex({x})",
        "complex?" => $"w_.OptComplex({x})",
        "double?" => $"w_.OptDouble({x})",
        "int32?" or "enum?" => $"w_.OptInt({x}.HasValue ? (int){x}.Value : (int?)null)",
        "int64?" => $"w_.OptLong({x})",
        "bool?" => $"w_.OptBool({x})",
        "handle" or "boxed" or "boxed?" or "snapshot" => $"w_.Obj({x})",
        "engine" => $"w_.Opaque(\"engine\")",
        "matrix" or "matrix&" => $"w_.Matrix({x})",
        "vector" or "vector&" => $"w_.Vector({x})",
        "span" => k.Element!.Name == "double" ? $"w_.Doubles({x})" : $"w_.Ints({x})",
        "jagged" => $"w_.Jagged<{CsNames.Of(k.Type.IsArray ? k.Type.GetElementType()! : k.Type.GetGenericArguments()[0])}>({Sequence(k.Type, x)})",
        "map" => $"w_.Map({x}, (w, v) => {Element(k.Element!, "v", "w")}, (w, v) => {Element(k.Value!, "v", "w")})",
        "array" => k.Element!.Name switch
        {
            "double" => $"w_.Doubles({x})",
            "int32" => $"w_.Ints({x})",
            _ => $"w_.List({Sequence(k.Type, x)}, (w, v) => {Element(k.Element!, "v", "w")})",
        },
        _ => throw new InvalidOperationException("no capture for " + k.Text),
    };

    private static string Sequence(Type collection, string x) =>
        collection.IsConstructionOf("System.ReadOnlySpan`1") ? $"({x}).ToArray()" : x;

    private static string Element(CKind e, string v, string w) => e.Name switch
    {
        "double" => $"{w}.Double({v})",
        "int32" or "enum" => $"{w}.Int((int)({v}))",
        "int64" => $"{w}.Long({v})",
        "bool" => $"{w}.Bool({v})",
        "string" => $"{w}.Str({v})",
        "date" => $"{w}.Date({v})",
        "date?" => $"{w}.OptDate({v})",
        "period" => $"{w}.Period({v})",
        "complex" => $"{w}.Complex({v})",
        "double?" => $"{w}.OptDouble({v})",
        "int32?" => $"{w}.OptInt({v})",
        "handle" => $"{w}.Obj({v})",
        _ => throw new InvalidOperationException("no element capture for " + e.Name),
    };

    // The result written after the call: a new object takes the next id.
    private static string Result(CKind k, string r, bool fresh) => k.Name switch
    {
        "handle" or "boxed" or "boxed?" or "snapshot" => $"w_.New({r})",
        "tuple" => "w_.Open(); " + string.Join(" ", k.Items.Select((item, i) => Result(item, $"{r}.Item{i + 1}", false) + ";")) + " w_.Close()",
        "distribution" => $"w_.Distribution({r})",
        "array" when k.Element!.Name == "handle" => $"w_.List({Sequence(k.Type, r)}, (w, v) => w.New(v))",
        _ => Capture(k, r),
    };

    private void Preset(StringBuilder cs, System.Reflection.ConstructorInfo ctor, List<PresetRow> rows, string twin)
    {
        ParameterInfo[] ps = ctor.GetParameters();
        string t = CsNames.Of(ctor.DeclaringType!);
        string args = string.Join(", ", ps.Select((_, i) => "a" + i));
        cs.AppendLine($"    public static {t} {twin}({string.Join(", ", ps.Select((p, i) => CsNames.Of(p.ParameterType) + " a" + i))})").AppendLine("    {");
        cs.AppendLine($"        var r_ = new {t}({args});");
        cs.AppendLine($"        if (!{Rec}.On || !{Rec}.UnderQuantLib) return r_;");
        foreach (PresetRow row in rows)
        {
            IReadOnlyList<PresetArgument> a = row.Construction.Arguments;
            if (a.Any(x => !x.IsConstant && x.Parameter < 0))
            {
                continue;
            }

            string test = string.Join(" && ", a.Select((x, i) => x.IsConstant ? Equal(ps[i].ParameterType, "a" + i, x.Constant) : "true").DefaultIfEmpty("true"));

            // The lookup takes the lambda's parameters the construction passes, in the lambda's order.
            CParam[] lookupParams = [.. row.Lookup!.Params.Skip(1)];
            var captures = new List<string> { "w_.Obj(null)", $"w_.Str({JsonSerializer.Serialize(row.Factory.Name)})" };
            int[] passed = row.Construction.PassedParameters();
            for (int k = 0; k < passed.Length; k++)
            {
                int ctorArg = Enumerable.Range(0, a.Count).First(i => a[i].Parameter == passed[k]);
                captures.Add(Capture(lookupParams[k + 1].Kind, "a" + ctorArg));
            }

            // The lookup stands for the constructor only where it builds too (the set's swap route compares a 365D
            // tenor with a year, which the coded preset doesn't).
            var lookup = (MethodInfo)row.Lookup.Member!;
            ParameterInfo[] lps = lookup.GetParameters();
            string call = $"{CsNames.Of(lookup.DeclaringType!)}.QuantLib.{lookup.Name}({JsonSerializer.Serialize(row.Factory.Name)}"
                + string.Concat(passed.Select((p, k) => $", ({CsNames.Of(lps[k + 1].ParameterType)})a{Enumerable.Range(0, a.Count).First(i => a[i].Parameter == p)}")) + ")";
            cs.AppendLine($"        if ({test} && {Rec}.Gives(() => {call})) {{ var w_ = {Rec}.Args(); {string.Join("; ", captures)}; w_.Result(); w_.New(r_); {Rec}.Call(\"{row.Lookup.CName}\", w_); {Rec}.Substitute(r_); return r_; }}");
        }

        cs.AppendLine("        return r_;").AppendLine("    }");
    }

    // A preset built by reflection (a test's table of every coded preset) goes through its constructor's twin, so the
    // trace writes it as its set's lookup too: the reflection calls' twins ask Reflected first.
    private static void Reflection(StringBuilder cs, List<(string Key, string Twin, string Site)> map, List<(System.Reflection.ConstructorInfo Ctor, string Twin)> presets)
    {
        cs.AppendLine("    public static object Reflected(global::System.Reflection.ConstructorInfo c, object[] a)").AppendLine("    {");
        foreach ((System.Reflection.ConstructorInfo ctor, string twin) in presets)
        {
            ParameterInfo[] ps = ctor.GetParameters();
            string types = string.Concat(ps.Select(p => ", typeof(" + CsNames.Of(p.ParameterType) + ")"));
            string args = string.Join(", ", ps.Select((p, i) => $"({CsNames.Of(p.ParameterType)})a[{i}]"));
            cs.AppendLine($"        if ({Rec}.Is(c, typeof({CsNames.Of(ctor.DeclaringType!)}){types})) return {twin}({args});");
        }

        cs.AppendLine("        return null;").AppendLine("    }");
        cs.AppendLine($"    public static object XCreateInstance(global::System.Type t) => {Rec}.CreateInstance(t);");
        cs.AppendLine($"    public static object XInvoke(global::System.Reflection.ConstructorInfo self, object[] a) => {Rec}.Invoke(self, a);");
        cs.AppendLine($"    public static object XInvokeWith(global::System.Reflection.ConstructorInfo self, global::System.Reflection.BindingFlags f, global::System.Reflection.Binder b, object[] a, global::System.Globalization.CultureInfo c) => {Rec}.Invoke(self, f, b, a, c);");
        map.Add(("System.Activator::CreateInstance(System.Type)", "XCreateInstance", "static"));
        map.Add(("System.Reflection.ConstructorInfo::Invoke(System.Object[])", "XInvoke", "instance"));
        map.Add(("System.Reflection.ConstructorInfo::Invoke(System.Reflection.BindingFlags,System.Reflection.Binder,System.Object[],System.Globalization.CultureInfo)", "XInvokeWith", "instance"));
    }

    // A record built by an object initializer or a with-expression mutates a fresh object through its init accessors
    // after the call site's constructor or clone; its twin marks the object pending, and the first call that takes it
    // writes it as the C ABI builds it: new, then a with_ per property that differs from the base.
    private void Records(StringBuilder cs, List<(string Key, string Twin, string Site)> map, ref int index)
    {
        var materialize = new StringBuilder();
        materialize.AppendLine("    public static bool Materialize(object o, object b)").AppendLine("    {").AppendLine("        switch (o)").AppendLine("        {");
        // Most derived first, so no case is subsumed by its base's.
        foreach (IGrouping<Type, CFunction> withs in surface.Functions.Where(f => f.Kind == "with").GroupBy(f => f.Type).OrderByDescending(g => Depth(g.Key)).ThenBy(g => g.Key.FullName, StringComparer.Ordinal))
        {
            Type t = withs.Key;
            string tc = CsNames.Of(t);
            CFunction? ctor = surface.Functions.FirstOrDefault(f => f.Kind == "new" && f.Type == t && f.Member is ConstructorInfo c && c.GetParameters().Length == 0);
            var required = t.GetProperties(BindingFlags.Public | BindingFlags.Instance).Where(p => p.Has("System.Runtime.CompilerServices.RequiredMemberAttribute")).OrderBy(p => p.MetadataToken).ToList();
            if (ctor != null)
            {
                string twin = "R" + index++;
                // A placeholder each required member's setter accepts, the call site's initializer then setting its own.
                string init = required.Count > 0 ? " { " + string.Join(", ", required.Select(r => r.Name + " = " + Placeholder(r.PropertyType))) + " }" : "()";
                cs.AppendLine($"    public static {tc} {twin}() {{ var r_ = new {tc}{init}; {Rec}.Pending(r_, null); return r_; }}");
                map.Add((((ConstructorInfo)ctor.Member!).MemberKey(), twin, "newobj"));
            }

            string clone = "R" + index++;
            cs.AppendLine($"    public static {tc} {clone}({tc} self) {{ var r_ = self with {{ }}; {Rec}.Pending(r_, self); return r_; }}");
            map.Add((t.KeyName() + "::<Clone>$()", clone, "instance"));
            materialize.AppendLine($"            case {tc} x_:").AppendLine("            {");
            materialize.AppendLine($"                var b_ = ({tc})b;").AppendLine("                long prev_;");
            if (ctor != null)
            {
                materialize.AppendLine("                if (b_ == null)").AppendLine("                {");
                string baseInit = required.Count > 0 ? " { " + string.Join(", ", required.Select(r => r.Name + " = x_." + r.Name)) + " }" : "()";
                materialize.AppendLine($"                    b_ = new {tc}{baseInit};");
                materialize.AppendLine($"                    var w_ = {Rec}.Args();");
                foreach (PropertyInfo r in required)
                {
                    CParam rp = ctor.Params.Single(q => string.Equals(q.Name, r.Name, StringComparison.OrdinalIgnoreCase));
                    materialize.AppendLine($"                    {Capture(rp.Kind, "x_." + r.Name)};");
                }

                materialize.AppendLine($"                    w_.Result(); prev_ = w_.NewTemporary(); {Rec}.Call(\"{ctor.CName}\", w_);").AppendLine("                }").AppendLine("                else");
            }
            else
            {
                materialize.AppendLine("                if (b_ == null) return false;").AppendLine("                else");
            }

            materialize.AppendLine("                {").AppendLine($"                    if ({Rec}.IdOrMaterialize(b_) is not {{ }} id_) return false;").AppendLine("                    prev_ = id_;").AppendLine("                }");
            foreach (CFunction w in withs)
            {
                string prop = w.Member!.Name;
                string pt = CsNames.Of(((PropertyInfo)w.Member).PropertyType);
                materialize.AppendLine($"                if (!global::System.Collections.Generic.EqualityComparer<{pt}>.Default.Equals(x_.{prop}, b_.{prop}))").AppendLine("                {");
                materialize.AppendLine($"                    var w_ = {Rec}.Args(); w_.Long(prev_); {Capture(w.Params[1].Kind, "x_." + prop)}; w_.Result(); prev_ = w_.NewTemporary(); {Rec}.Call(\"{w.CName}\", w_);").AppendLine("                }");
            }

            materialize.AppendLine($"                {Rec}.Rename(prev_, o);").AppendLine("                return true;").AppendLine("            }");
        }

        materialize.AppendLine("            default: return false;").AppendLine("        }").AppendLine("    }");
        cs.Append(materialize);
    }

    // A generator's draws, written as Draws calls along its snapshots: each draw of one value or one sequence is
    // Draws(snapshot, 1), and the generator is then the call's next snapshot; a clone shares its source's snapshot. A
    // draw that isn't the snapshot's (C# moved the generator where the trace can't follow: SkipTo, an integer draw, an
    // object drawing from it) forgets the generator.
    private void Generators(StringBuilder cs, List<(string Key, string Twin, string Site)> map, ref int index)
    {
        CFunction[] draws = [.. surface.Functions.Where(f => f.Kind == "draws").OrderByDescending(f => Depth(f.Type)).ThenBy(f => f.CName, StringComparer.Ordinal)];
        if (draws.Length == 0)
        {
            return;
        }

        foreach (bool sequence in new[] { false, true })
        {
            CFunction[] kinds = [.. draws.Where(f => (f.Return!.Name == "sequences") == sequence)];
            if (kinds.Length == 0)
            {
                continue;
            }

            string member = sequence ? "NextSequence" : "Next";
            string sample = sequence ? "global::NanoQL.Methods.Sample<global::System.ReadOnlyMemory<double>>" : "global::NanoQL.Methods.Sample<double>";
            string iface = sequence ? "NanoQL.Numerics.IRsg" : "NanoQL.Numerics.IRng";

            // The receivers: the interface, and each generator type that declares the member.
            var receivers = new List<Type> { kinds[0].Type.GetInterfaces().Single(i => i.FullName == iface) };
            receivers.AddRange(kinds.Select(f => f.Type).Where(t => t.GetMethod(member, BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly, Type.EmptyTypes) != null));
            foreach (Type receiver in receivers)
            {
                string twin = "G" + index++;
                string self = CsNames.Of(receiver);
                cs.AppendLine($"    public static {sample} {twin}({self} self)").AppendLine("    {");
                cs.AppendLine($"        if (!{Rec}.On) return self.{member}();");
                cs.Append("        string fn_ = ");
                foreach (CFunction f in kinds.Where(f => receiver.IsAssignableFrom(f.Type)))
                {
                    cs.Append($"self is {CsNames.Of(f.Type)} ? \"{f.CName}\" : ");
                }

                cs.AppendLine("null;");
                cs.AppendLine($"        long? id_ = fn_ == null ? null : {Rec}.Id(self);");
                cs.AppendLine($"        if (id_ == null) return self.{member}();");
                cs.AppendLine($"        {Rec}.Enter();");
                cs.AppendLine($"        {sample} r_;");
                cs.AppendLine($"        try {{ r_ = self.{member}(); }} finally {{ {Rec}.Leave(); }}");
                cs.AppendLine($"        if (!{Rec}.Follows(self, r_)) {{ {Rec}.Forget(self); return r_; }}");
                cs.AppendLine($"        var w_ = {Rec}.Args(); w_.Long(id_.Value); w_.Int(1); w_.Result(); w_.Open();");
                cs.AppendLine(sequence
                    ? "        double[] v_ = r_.Value.ToArray(); w_.Doubles(v_); w_.Doubles(new[] { r_.Weight }); w_.Int(v_.Length);"
                    : "        w_.Doubles(new[] { r_.Value }); w_.Doubles(new[] { r_.Weight });");
                cs.AppendLine($"        long next_ = w_.NewTemporary(); w_.Close(); {Rec}.Call(fn_, w_); {Rec}.Rename(next_, self);");
                cs.AppendLine("        return r_;").AppendLine("    }");
                map.Add((receiver.KeyName() + "::" + member + "()", twin, "instance"));

                if (receiver.GetMethod("Clone", BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly, Type.EmptyTypes) is { } clone && clone.ReturnType.FullName != "System.Object")
                {
                    string cloneTwin = "G" + index++;
                    string ret = CsNames.Of(clone.ReturnType);
                    cs.AppendLine($"    public static {ret} {cloneTwin}({self} self) {{ var r_ = self.Clone(); if ({Rec}.On && {Rec}.Id(self) is {{ }} id_) {{ {Rec}.Rename(id_, r_); {Rec}.KeepFrom(r_, self); }} return r_; }}");
                    map.Add((receiver.KeyName() + "::Clone()", cloneTwin, "instance"));
                }
            }
        }
    }

    private static string Placeholder(Type t) => t.FullName == "NanoQL.Time.Date" ? "new global::NanoQL.Time.Date(367)" : "default";

    private static int Depth(Type t)
    {
        int d = 0;
        for (Type? x = t; x != null; x = x.BaseType)
        {
            d++;
        }

        return d;
    }

    private static string Equal(Type t, string a, object? constant) => constant switch
    {
        null => $"{a} == null",
        string s => $"{a} == {JsonSerializer.Serialize(s)}",
        double d => $"{a} == {CsNames.Double(d)}",
        _ when t.IsEnum => $"(long){a} == {Convert.ToInt64(constant, System.Globalization.CultureInfo.InvariantCulture)}L",
        bool b => $"{a} == {(b ? "true" : "false")}",
        int i when t.FullName == "System.Boolean" => $"{a} == {(i != 0 ? "true" : "false")}",
        _ => $"{a} == {Convert.ToString(constant, System.Globalization.CultureInfo.InvariantCulture)}",
    };
}
