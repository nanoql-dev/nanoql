"""The QLNet parity table, a migration map: each QuantLib 1.44 class in the units nanoql ports, beside nanoql's type and
QLNet's type of the same name, with the method and its counts at the table's foot.

Usage: .venv\\Scripts\\python -I tools/docs/qlnet-parity.py <QuantLib v1.44 worktree> <QLNet v1.13.2 checkout>
       [--root <repository>] [--out <file>] [--check]

Its inputs are public: the units, and each unit's nanoql files, come from the checkout's docs/porting-map.md (ported or
partial); a unit's classes from its header, outside its detail namespace. A class's nanoql route: the type of its
name; else a type of its name in another case, as an interface ("I" + name), or without QuantLib's Generic, Impl or _2
marks (renamed); else the unit's nanoql files, where the class is an implementation detail. QLNet's column: a class,
struct, interface or enum QLNet declares under src/QLNet with the class's name. A type of the same name isn't proof of
the same API, and the page says so. It writes docs/parity/qlnet.md by default; with --check it writes nothing and
exits 1 if the committed table differs from a fresh one.
"""
import collections
import os
import re
import sys

CLS = re.compile(r"^\s*(?:template\s*<[^;{]*>\s*)?class\s+(?:QL_\w+\s+)?([A-Z]\w+)\s*(?::|\{)", re.M)
DETAIL = re.compile(r"namespace\s+detail\s*\{.*?\n\s*\}\s*//\s*namespace detail", re.S)
CS_TYPE = re.compile(r"^\s*(?:(?:public|internal|private|protected|sealed|abstract|static|partial|readonly|ref|unsafe|"
                     r"new|file)\s+)*(?:class|struct|interface|enum|record(?:\s+struct|\s+class)?)\s+([A-Za-z_]\w*)",
                     re.M)
UNIT_ROW = re.compile(r"^\| `([^`]+)` \| (ported|partial)\b[^|]*\|([^|]*)\|")
HEADER = """<!--
  SPDX-FileCopyrightText: 2026 The nanoql Authors
  SPDX-License-Identifier: Apache-2.0
-->
<!-- Generated by tools/docs/qlnet-parity.py; don't edit by hand. -->
"""


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read()


def units_of(root):
    """The ported or partial units under ql/, each with its nanoql files, from the porting map."""
    units, files, section = {}, {}, None
    for line in read(os.path.join(root, "docs", "porting-map.md")).splitlines():
        m = re.match(r"^### `([^`]+)`", line)
        if m:
            section = m.group(1).rstrip("/")
            continue
        m = UNIT_ROW.match(line)
        if m and section and section.startswith("ql"):
            unit = f"{section}/{m.group(1)}".replace("//", "/")
            units[unit] = m.group(2)
            files[unit] = m.group(3).strip()
    return units, files


def cs_types(folder):
    names = set()
    for d, _, found in os.walk(folder):
        for f in found:
            if f.endswith(".cs"):
                names.update(CS_TYPE.findall(read(os.path.join(d, f))))
    return names


def table(ql, qlnet_root, root):
    units, files = units_of(root)
    qlnet = cs_types(os.path.join(qlnet_root, "src", "QLNet"))
    nanoql = cs_types(os.path.join(root, "src"))
    lower = {n.lower(): n for n in nanoql}

    def route(c, unit):
        for candidate in (c, "I" + c, re.sub(r"^Generic", "", c), re.sub(r"(_?Impl|_2)$", "", c)):
            if candidate in nanoql:
                return candidate, ("same" if candidate == c else "renamed")
        if c.lower() in lower:
            return lower[c.lower()], "renamed"
        return files.get(unit, ""), "inside"

    rows = []
    for unit in sorted(units):
        hpp = os.path.join(ql, *(unit + ".hpp").split("/"))
        if not os.path.isfile(hpp):
            continue
        for c in sorted(set(CLS.findall(DETAIL.sub("", read(hpp))))):
            found, how = route(c, unit)
            rows.append((unit, c, found, how, c in qlnet))
    return units, rows


def render(units, rows):
    n = len(rows)
    how = collections.Counter(r[3] for r in rows)
    theirs = sum(r[4] for r in rows)
    out = [HEADER, "| QuantLib unit | QuantLib class | nanoql | QLNet 1.13.2 |", "|---|---|---|---|"]
    for unit, c, found, kind, has in rows:
        cell = f"`{found}`" if kind == "same" else f"`{found}` (renamed)" if kind == "renamed" else f"inside {found}"
        out.append(f"| `{unit}` | `{c}` | {cell} | {('`' + c + '`') if has else 'no type of the name'} |")
    out += [
        "",
        f"**The method.** The {len(units):,} QuantLib 1.44 units nanoql ports, wholly or in part, hold {n:,} classes, read "
        "from each unit's header outside its detail namespace. nanoql has a type of the same name for "
        f"{how['same']:,} of them; {how['renamed']:,} under another name (an interface's \"I\", QuantLib's Impl merged "
        f"into its type, a case change); and {how['inside']:,} inside their unit's files, where the class is an "
        f"implementation detail. QLNet 1.13.2 declares a type of the same name for {theirs:,} of the {n:,} "
        f"({100 * theirs / n:.0f}%). A type of the same name isn't proof of the same API.",
    ]
    return "\n".join(out) + "\n"


def main(argv):
    valued = ("--root", "--out")
    if len(argv) < 2 or any(a in valued and (k + 1 == len(argv) or argv[k + 1].startswith("--"))
                            for k, a in enumerate(argv)):
        print(__doc__)
        return 2
    ql, qlnet_root = argv[0], argv[1]
    root = argv[argv.index("--root") + 1] if "--root" in argv else os.path.dirname(os.path.dirname(
        os.path.dirname(os.path.abspath(__file__))))
    out = argv[argv.index("--out") + 1] if "--out" in argv else os.path.join(root, "docs", "parity", "qlnet.md")
    units, rows = table(ql, qlnet_root, root)
    text = render(units, rows)
    if "--check" in argv:
        current = read(out) if os.path.isfile(out) else ""
        if current != text:
            print(f"QLNet parity: {out} differs from a fresh table")
            return 1
        print("QLNet parity: reproduces")
        return 0
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {out}: {len(rows):,} classes in {len(units):,} units")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv[1:]))
