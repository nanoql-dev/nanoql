"""The extension points: the public bases QuantLib's hierarchy derives from, abstract or unsealed, and the interfaces
public types implement, which a user's own types can derive from, listed by namespace, each linked to its API page.

Usage: .venv\\Scripts\\python -I tools/docs/extension-points.py <docfx api folder> <out.md> [--root <repository>]

It reads docfx's own metadata of the built assemblies (the api folder's .yml files). A class is listed when it is
public, abstract or not sealed, not static, a public type derives from it (docfx's derivedClasses), and another
assembly can derive from it: it has no declared constructor, or one that is public, protected or protected internal.
docfx's metadata leaves out private protected constructors, so the constructors are read from the class's source
files under the repository. An interface is listed when a public type implements it. Each entry is an xref to its
page, so docfx fails a link it can't resolve.
"""
import collections
import glob
import os
import re
import sys

HEADER = """<!--
  SPDX-FileCopyrightText: 2026 The nanoql Authors
  SPDX-License-Identifier: Apache-2.0
-->
<!-- Generated by tools/docs/extension-points.py; don't edit by hand. -->

# Extension points

The public bases QuantLib's hierarchy derives from, abstract or unsealed, and the interfaces public types implement:
types of your own derive from them or implement them. A class is listed only where another assembly can derive from
it.

"""
DERIVABLE = {"public", "protected", "protected internal", "internal protected"}


def first_item(text):
    parts = text.split("\n- uid:", 2)
    return "- uid:" + parts[1] if len(parts) > 1 else text


NAMESPACE = re.compile(r"^\s*namespace\s+([\w.]+)\s*[;{]", re.M)
CLASS = re.compile(r"\b(?<!record )(?:class|record(?:\s+class)?)\s+([A-Za-z_]\w*)\s*(<[^>(]*>)?")


def class_files(root):
    """Each class declared under src/, by (namespace, name, generic arity), with the files declaring it (partials)."""
    index = collections.defaultdict(list)
    for path in glob.glob(os.path.join(root, "src", "**", "*.cs"), recursive=True):
        with open(path, encoding="utf-8-sig") as f:
            text = f.read()
        ns = NAMESPACE.search(text)
        for m in CLASS.finditer(text):
            arity = m.group(2).count(",") + 1 if m.group(2) else 0
            index[(ns.group(1) if ns else "", m.group(1), arity)].append((path, text))
    return index


def constructors(index, uid):
    """The access of each constructor the class's source files declare, or None when no file declares it."""
    head, _, arity = uid.partition("`")
    ns, _, name = head.rpartition(".")
    files = index.get((ns, name, int(arity) if arity else 0))
    while not files and "." in ns:
        # a nested class: its uid's namespace runs on through its outer types
        outer = ns.rsplit(".", 1)[1]
        ns = ns.rsplit(".", 1)[0]
        files = [f for f in index.get((ns, name, int(arity) if arity else 0), []) if re.search(rf"\b{outer}\b", f[1])]
    if not files:
        return None
    declaration = re.compile(rf"^\s*((?:(?:public|protected|internal|private)\s+){{1,2}})(?:unsafe\s+)?"
                             rf"{re.escape(name)}\s*\(", re.M)
    primary = re.compile(rf"\b(?:class|record)\s+{re.escape(name)}\s*(?:<[^>]*>)?\s*\(")
    found = []
    for _, text in files:
        found += [" ".join(m.group(1).split()) for m in declaration.finditer(text)]
        if primary.search(text):
            found.append("public")
        if re.search(rf"\brecord\s+(?:class\s+)?{re.escape(name)}\b", text):
            found.append("protected")  # a record's copy constructor, which the compiler declares protected
    return found


def points(api, root):
    types, implemented, index = {}, collections.Counter(), class_files(root)
    for path in glob.glob(os.path.join(api, "*.yml")):
        with open(path, encoding="utf-8") as f:
            first = first_item(f.read())
        uid = re.search(r"^- uid: (\S+)", first, re.M)
        kind = re.search(r"^  type: (\w+)", first, re.M)
        if not uid or not kind or kind.group(1) not in ("Class", "Interface"):
            continue
        syntax = re.search(r"^    content: '?(.*?)'?$", first, re.M)
        words = set(syntax.group(1).split(":")[0].split()) if syntax else set()
        derived = re.search(r"^  derivedClasses:\s*\n((?:  - .*\n)+)", first, re.M)
        impl = re.search(r"^  implements:\s*\n((?:  - .*\n)+)", first, re.M)
        if impl:
            for i in re.findall(r"  - (\S+)", impl.group(1)):
                implemented[i] += 1
        types[uid.group(1)] = (kind.group(1), words, bool(derived))
    found, closed = [], []
    for uid, (kind, words, derived) in sorted(types.items()):
        if kind == "Interface":
            if implemented.get(uid):
                found.append((uid, "interface"))
            continue
        if "sealed" in words or "static" in words or not derived:
            continue
        ctors = constructors(index, uid)
        if ctors is None:
            raise SystemExit(f"{uid}: no source file under src/ declares it")
        if ctors and not any(c in DERIVABLE for c in ctors):
            closed.append(uid)
            continue
        found.append((uid, "abstract class" if "abstract" in words else "unsealed class"))
    return found, closed


def main(argv):
    valued = ("--root",)
    if len(argv) < 2 or any(a in valued and (k + 1 == len(argv) or argv[k + 1].startswith("--"))
                            for k, a in enumerate(argv)):
        print(__doc__)
        return 2
    api, out = argv[0], argv[1]
    root = argv[argv.index("--root") + 1] if "--root" in argv else os.path.dirname(os.path.dirname(
        os.path.dirname(os.path.abspath(__file__))))
    found, closed = points(api, root)
    by_ns = collections.defaultdict(list)
    for uid, kind in found:
        by_ns[uid.split("`")[0].rsplit(".", 1)[0]].append((uid, kind))
    with open(out, "w", encoding="utf-8", newline="\n") as w:
        w.write(HEADER)
        for ns in sorted(by_ns):
            w.write(f"## {ns}\n\n" + "".join(f"- <xref:{u}> ({k})\n" for u, k in sorted(by_ns[ns])) + "\n")
    counts = collections.Counter(k for _, k in found)
    print(f"{len(found)} extension points: {dict(counts)}; {len(closed)} classes no other assembly can derive: "
          + ", ".join(closed))
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv[1:]))
