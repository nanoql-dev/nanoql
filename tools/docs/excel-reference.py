"""The Excel function reference: the add-in's listed functions on a page per task, each with its description and its
arguments' as Excel's Function Wizard shows them, and a link to its C# member's API page; a page of the names users
type; and the functions the completeness check withholds, with what each lacks.

Usage: .venv\\Scripts\\python -I tools/docs/excel-reference.py <generated sources> <out folder> [--root <repository>]

<generated sources> is the folder `nanoql-bind excel build --experimental --no-pack` writes the add-in's sources into
(XlFunctions*.g.cs). The checkout gives the rest: bindings/excel/list.json (the listed types and their tasks),
bindings/excel/functions.json (the experimental build's functions and the withheld ones), bindings/surface.json, and
the convention presets under src/NanoQL.Extensions/Conventions/Presets/.

- **Placement:** a function's own type's task, else every task of a listed type that inherits its type or takes it as
  an extension's first parameter; a function reaching several tasks is listed under each. A function it can't place
  stops the script.
- **Texts:** the generated add-in's own [ExcelFunction] and [ExcelArgument] descriptions, read from its sources, so the
  page says what the Function Wizard says.
- **Links:** an xref to the member's API page by docfx's uid, from surface.json's key: the declaring type, where an
  inherited member's page is; a constructor's #ctor overloads, an indexer's Item, a property or field by its name; the
  type itself for a struct's implicit constructor and for the binding's own constructs (bind, bindon, with, draws).
  docfx fails a link it can't resolve.
- **Names:** each enum's members (surface.json), and the presets' calendars, day counters and indexes.

Writes excel-<task>.md per task, excel-names.md and excel-withheld.md into the out folder.
"""
import collections
import glob
import json
import os
import re
import sys

FN = re.compile(r'\[ExcelFunction\(Name = "([^"]+)"[^\]]*?Description = ("(?:[^"\\]|\\.)*")\)\]\s*'
                r'public static object \w+\((.*?)\)\s*=>', re.S)
ARG = re.compile(r'\[ExcelArgument\(Name = "([^"]+)", Description = ("(?:[^"\\]|\\.)*")\)\]')
PRESET = re.compile(r'<(?:\w+Preset|IborIndex|OvernightIndex|SwapIndex|YoYInflationIndex|ZeroInflationIndex) '
                    r'name="([^"]+)"')
HEADER = """<!--
  SPDX-FileCopyrightText: 2026 The nanoql Authors
  SPDX-License-Identifier: Apache-2.0
-->
<!-- Generated by tools/docs/excel-reference.py; don't edit by hand. -->

"""


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def definition(name):
    """A type's name without its type arguments, given as surface.json writes them ([...] or <...>)."""
    return name.split("[", 1)[0].split("<", 1)[0]


class Reference:
    def __init__(self, root, generated):
        self.listed = {e["type"]: e["task"] for e in load(os.path.join(root, "bindings", "excel", "list.json"))["types"]}
        manifest = load(os.path.join(root, "bindings", "excel", "functions.json"))
        self.functions, self.withheld = manifest["functions"], manifest.get("withheld", [])
        surface = load(os.path.join(root, "bindings", "surface.json"))
        self.types, self.enums = surface["types"], surface["enums"]
        self.surface_fns = {g["name"]: g for g in surface["functions"]}
        self.by_name = {t["name"]: t for t in self.types}
        self.presets = os.path.join(root, "src", "NanoQL.Extensions", "Conventions", "Presets")
        self.texts = {}
        for path in sorted(glob.glob(os.path.join(generated, "**", "XlFunctions*.g.cs"), recursive=True)):
            with open(path, encoding="utf-8") as f:
                for m in FN.finditer(f.read()):
                    self.texts[m.group(1)] = (json.loads(m.group(2)),
                                              [(a, json.loads(d)) for a, d in ARG.findall(m.group(3))])
        self.tasks_of = collections.defaultdict(set)
        for full, task in self.listed.items():
            closed = {t["name"] for t in self.types if definition(t["name"]) == full}
            for a in self.ancestors(full) | {full} | set().union(*(self.ancestors(c) for c in closed)):
                self.tasks_of[definition(a)].add(task)

    def ancestors(self, name):
        seen, todo = set(), [name]
        while todo:
            n = todo.pop()
            if n in seen or n not in self.by_name:
                continue
            seen.add(n)
            t = self.by_name[n]
            todo += ([t["base"]] if t.get("base") else []) + list(t.get("interfaces") or [])
        return seen

    def uid(self, g):
        """docfx's uid of the member's page, its # encoded (a link's # starts a fragment)."""
        t = definition(g["type"])
        member, kind = g["member"], g["kind"]
        if kind in ("bind", "bindon", "with", "draws"):
            return t
        declaring = g.get("key", "").split("::", 1)[0]
        if declaring:
            t = re.sub(r"<.*>$", "", declaring)
        if kind == "indexer":
            return f"{t}.Item*"
        if kind == "new" or member in (".ctor", "#ctor"):
            if g.get("key", "").endswith("::.ctor()") and self.by_name.get(definition(g["type"]), {}).get("shape") == \
                    "struct":
                return t
            return f"{t}.%23ctor*"
        if member.startswith("get_"):
            return f"{t}.{member[4:]}"
        if kind == "field":
            return f"{t}.{member}"
        return f"{t}.{member}*"

    def place(self, g):
        declaring = definition(g["type"])
        if declaring in self.listed:
            return {self.listed[declaring]}
        reach = set(self.tasks_of.get(declaring.split("`")[0], set()) | self.tasks_of.get(declaring, set()))
        if not reach and g.get("static") and g.get("params"):
            reach = set(self.tasks_of.get(definition(g["params"][0].get("type", "")), set()))
        return reach

    def write(self, out):
        pages, unplaced, untexted = collections.defaultdict(list), [], []
        for f in self.functions:
            g = self.surface_fns.get(f["c"])
            if g is None:
                unplaced.append(f["excel"])
                continue
            reach = self.place(g)
            if not reach:
                unplaced.append(f["excel"])
            if f["excel"] not in self.texts:
                untexted.append(f["excel"])
            for task in reach:
                pages[task].append((f, g))
        if unplaced or untexted:
            raise SystemExit(f"functions unplaced: {unplaced[:10]} ({len(unplaced)}); without the generated text: "
                             f"{untexted[:10]} ({len(untexted)})")
        os.makedirs(out, exist_ok=True)
        for task, items in sorted(pages.items()):
            lines = [HEADER + f"# Excel functions: {task}\n"]
            for f, g in sorted(items, key=lambda x: x[0]["excel"].lower()):
                desc, args = self.texts[f["excel"]]
                lines.append(f"## {f['excel']}\n\n{desc}\n")
                if args:
                    lines.append("| Argument | Description |\n|---|---|\n" + "".join(
                        f"| `{a}` | {d.replace('|', '&#124;')} |\n" for a, d in args))
                lines.append(f"Returns {f['returns']}{' (experimental)' if f['experimental'] else ''}. "
                             f"C#: <xref:{self.uid(g)}>\n")
            self.save(os.path.join(out, f"excel-{task.replace(' ', '-')}.md"), "\n".join(lines))
        names = [HEADER + "# Names in Excel\n\n## Enumerations\n"]
        for e in sorted(self.enums, key=lambda e: e["name"]):
            names.append(f"- `{e['name'].split('.')[-1]}`: " + ", ".join(f"`{m[0]}`" for m in e["members"]))
        for kind, file in (("Calendars", "calendars.xml"), ("Day counters", "daycounters.xml"),
                           ("Indexes", "indexes.xml")):
            with open(os.path.join(self.presets, file), encoding="utf-8") as f:
                found = PRESET.findall(f.read())
            names.append(f"\n## {kind}\n\n" + ", ".join(f"`{n}`" for n in found))
        self.save(os.path.join(out, "excel-names.md"), "\n".join(names) + "\n")
        withheld = [HEADER + "# Functions withheld\n",
                    "The completeness check withholds a function whose parameters or result need a type the add-in "
                    "doesn't carry. Each is listed with what it lacks.\n", "| Function | Lacks |", "|---|---|"]
        # A lack is a type, linked, or the check's words for what no type names ("an engine no listed engine binds").
        withheld += [f"| `{w['excel']}` | {', '.join(t if ' ' in t else f'<xref:{t}>' for t in w['lacks'])} |"
                     for w in sorted(self.withheld, key=lambda w: w["excel"].lower())]
        self.save(os.path.join(out, "excel-withheld.md"), "\n".join(withheld) + "\n")
        rows = sum(len(v) for v in pages.values())
        print(f"{len(self.functions):,} functions in {rows:,} rows under {len(pages)} tasks; "
              f"{len(self.enums)} enums; {len(self.withheld)} withheld")

    @staticmethod
    def save(path, text):
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    root = argv[argv.index("--root") + 1] if "--root" in argv else os.path.dirname(os.path.dirname(
        os.path.dirname(os.path.abspath(__file__))))
    Reference(root, argv[0]).write(argv[1])
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv[1:]))
