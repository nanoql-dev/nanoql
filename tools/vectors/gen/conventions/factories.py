"""The coded presets' constructors, by preset name, written from the presets files: every calendar, day counter and
currency the files name, presets and QuantLib's own aliases alike (an FpML code names no coded preset). The table is
the only place the extensions build a coded preset, so a set builds each as its own class, through no reflection.
Writes src/NanoQL.Extensions/Conventions/PresetFactories.cs; the extensions' source guard checks that nothing else
builds one."""
import os
import re
import sys

_dir = os.path.dirname(os.path.abspath(__file__))
while not os.path.isfile(os.path.join(_dir, "conventions.py")):
    _dir = os.path.dirname(_dir)
sys.path.insert(0, _dir)

import conventions as c  # noqa: E402

OUTPUT = "src/NanoQL.Extensions/Conventions/PresetFactories.cs"
PRESETS = os.path.join(c.REPO, "src", "NanoQL.Extensions", "Conventions", "Presets")
FLAGGED = {"Actual360", "Actual36525", "Actual366"}
CONVENTIONS = {"Actual365Fixed": "Actual365FixedConvention", "ActualActual": "ActualActualConvention",
               "Thirty360": "Thirty360Convention"}


def names(file, elements):
    text = open(os.path.join(PRESETS, file), encoding="utf-8").read()
    return [m.group(2) for m in re.finditer(r'<(\w+) name="([^"]+)"', text) if m.group(1) in elements]


def calendar(name):
    t, _, market = name.partition(".")
    return f"new {t}({t}Market.{market})" if market else f"new {t}()"


def day_counter(name):
    t, _, member = name.partition(".")
    if not member:
        return f"new {t}()"
    if t in FLAGGED:
        assert member == "IncludeLastDay", name
        return f"new {t}(true)"
    return f"new {t}({CONVENTIONS[t]}.{member})"


def table(field, kind, entries):
    lines = [f"    public static readonly FrozenDictionary<string, Func<{kind}>> {field} =",
             f"        new Dictionary<string, Func<{kind}>>(StringComparer.Ordinal)", "        {"]
    lines += [f'            ["{n}"] = static () => {e},' for n, e in entries]
    lines += ["        }.ToFrozenDictionary(StringComparer.Ordinal);"]
    return lines


def source():
    calendars = sorted(names("calendars.xml", {"CalendarPreset", "Alias"}))
    day_counters = sorted(names("daycounters.xml", {"DayCounterPreset", "Alias"}))
    currencies = sorted(names("currencies.xml", {"CurrencyPreset"}))
    lines = [
        "// SPDX-FileCopyrightText: 2026 The nanoql Authors",
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by tools/vectors/gen/conventions/factories.py from the presets files; regenerate, don't edit.",
        "",
        "using System.Collections.Frozen;",
        "using NanoQL.Currencies;",
        "using NanoQL.Time;",
        "",
        "namespace NanoQL.Extensions.Conventions;",
        "",
        "// The coded presets' constructors by preset name: the only place the extensions build one, so a set builds each",
        "// as its own class, its values read through the set it is built in.",
        "internal static class PresetFactories",
        "{",
    ]
    lines += table("Calendars", "Calendar", [(n, calendar(n)) for n in calendars]) + [""]
    lines += table("DayCounters", "DayCounter", [(n, day_counter(n)) for n in day_counters]) + [""]
    lines += table("Currencies", "Currency", [(n, f"new {n}Currency()") for n in currencies])
    lines += ["}"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    root = sys.argv[1] if len(sys.argv) > 1 else c.REPO
    path = os.path.join(root, *OUTPUT.split("/"))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(source().encode("utf-8"))
