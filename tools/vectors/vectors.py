"""Shared helpers for the vector generators under tools/vectors/gen/ (docs/porting-playbook.md §7.2).

A generator builds its cases with these helpers and calls main(), which writes tests/vectors/<path>.json, where
<path> is the generator's own path under gen/ without ".py". Run a generator with the venv's interpreter:

    .venv\\Scripts\\python -I tools/vectors/gen/<path>.py [<output root>]

The output root defaults to the repository's tests/vectors; tools/vectors/reproduce.py passes a temporary one.
"""
import json
import math
import os
import sys

import QuantLib as ql

QUANTLIB = "1.44"
SEED = 20261016

TOOLS_VECTORS = os.path.dirname(os.path.abspath(__file__))
GEN_ROOT = os.path.join(TOOLS_VECTORS, "gen")
REPO = os.path.dirname(os.path.dirname(TOOLS_VECTORS))
DEFAULT_OUT = os.path.join(REPO, "tests", "vectors")

# The per-file size budget (docs/porting-playbook.md §7.2).
MAX_BYTES = 1024 * 1024

if ql.__version__ != QUANTLIB:
    raise RuntimeError(f"the vectors are generated by QuantLib-Python {QUANTLIB}, not {ql.__version__}")

# QuantLib's null sentinels, as the wheel returns them.
NULL_REAL = ql.nullDouble()
NULL_INTEGER = ql.nullInt()


def enc(x):
    """The vector encoding: dates as serial numbers, enums as QuantLib's integers, NaN and the infinities as the
    strings "NaN", "Infinity" and "-Infinity", and QuantLib's null sentinels (Null<Real>, Null<Integer>, Date()) as
    None. Lists, tuples and dicts are encoded element by element."""
    if isinstance(x, ql.Date):
        return None if x == ql.Date() else x.serialNumber()
    if isinstance(x, bool):
        return x
    if isinstance(x, int):
        return None if x == NULL_INTEGER else x
    if isinstance(x, float):
        if math.isnan(x):
            return "NaN"
        if math.isinf(x):
            return "Infinity" if x > 0 else "-Infinity"
        return None if x == NULL_REAL else x
    if isinstance(x, (list, tuple)):
        return [enc(v) for v in x]
    if isinstance(x, dict):
        return {k: enc(v) for k, v in x.items()}
    if x is None or isinstance(x, str):
        return x
    raise TypeError(f"no vector encoding for {type(x).__name__}")


def settings(evaluation_date, include_reference_date_events=False, include_todays_cash_flows=None,
             enforces_todays_historic_fixings=False):
    """Sets every Settings value QuantLib reads, and returns them as a case's inputs.settings."""
    s = ql.Settings.instance()
    s.evaluationDate = evaluation_date
    s.includeReferenceDateEvents = include_reference_date_events
    s.includeTodaysCashFlows = include_todays_cash_flows
    s.enforcesTodaysHistoricFixings = enforces_todays_historic_fixings
    return {"evaluationDate": evaluation_date.serialNumber(),
            "includeReferenceDateEvents": include_reference_date_events,
            "includeTodaysCashFlows": include_todays_cash_flows,
            "enforcesTodaysHistoricFixings": enforces_todays_historic_fixings}


THROWS = {"throws": True}


def attempt(f):
    """f()'s encoded value, or {"throws": true} where QuantLib throws."""
    try:
        return enc(f())
    except RuntimeError:
        return dict(THROWS)


def result(f):
    """f()'s encoded value, or None where QuantLib throws "not available" or "not provided" on reading a null
    result, which nanoql returns as null."""
    try:
        return enc(f())
    except RuntimeError as e:
        text = str(e)
        if "not available" in text or "not provided" in text:
            return None
        raise


def amount(value, scale):
    """An amount compared with its own scale (docs/porting-playbook.md §7.3); one scalar, so one output."""
    if isinstance(value, (list, tuple, dict)):
        raise TypeError("amount() takes one value; scale each element of a list on its own")
    v = enc(value)
    return v if v is None or isinstance(v, (str, dict)) else {"value": v, "scale": float(scale)}


def count_outputs(expected):
    """The outputs an expected value holds: an array counts its elements; a {value, scale} object or a
    {"throws": true} counts once; any other scalar counts once."""
    if isinstance(expected, dict):
        if "throws" in expected or "value" in expected:
            return 1
        raise ValueError(f"an expected value is a scalar, an array, {{value, scale}} or {{throws}}: {expected}")
    if isinstance(expected, list):
        return sum(count_outputs(x) for x in expected)
    return 1


def count_overridden(expected):
    if isinstance(expected, dict):
        return 1 if "tolerance" in expected else 0
    if isinstance(expected, list):
        return sum(count_overridden(x) for x in expected)
    return 0


def check_override(expected):
    if isinstance(expected, dict) and "tolerance" in expected and not expected.get("reason"):
        raise ValueError("a tolerance override needs a reason naming its measured cause")
    if isinstance(expected, list):
        for x in expected:
            check_override(x)


def document(generator_file, upstream, cases, seed=SEED):
    rel = os.path.relpath(os.path.abspath(generator_file), GEN_ROOT).replace(os.sep, "/")
    assert rel.endswith(".py") and not rel.startswith(".."), rel
    for c in cases:
        assert set(c) == {"name", "inputs", "expected"}, c.get("name")
        assert "settings" in c["inputs"], c["name"]
        for value in c["expected"].values():
            count_outputs(value)
            check_override(value)
    doc = {"upstream": upstream, "quantlib": QUANTLIB, "generator": "tools/vectors/gen/" + rel, "seed": seed,
           "cases": cases}
    return rel[:-3], json.dumps(doc, separators=(",", ":"), ensure_ascii=False, allow_nan=False) + "\n"


def main(generator_file, upstream, make_cases, seed=SEED):
    """Writes a generator's file under the output root given as its first argument (default tests/vectors)."""
    out_root = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    rel, text = document(generator_file, upstream, make_cases(), seed)
    data = text.encode("utf-8")
    if len(data) > MAX_BYTES:
        raise SystemExit(f"{rel}.json is {len(data)} bytes, over the 1 MiB budget")
    path = os.path.join(out_root, *rel.split("/")) + ".json"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)
