using System.Collections;
using System.Globalization;
using System.Text;

namespace NanoQL.QLNetVectors;

/// <summary>
/// One vector file in the vectors' format (docs/porting-playbook.md §7.2), written in the bytes
/// <c>tools/vectors/vectors.py</c> writes: compact JSON, keys in insertion order, non-ASCII text as is, a real as
/// Python's <c>repr</c> gives it, NaN and the infinities as the strings <c>"NaN"</c>, <c>"Infinity"</c> and
/// <c>"-Infinity"</c>, and one line break at the end. The pin field is <c>"qlnet": "1.13.2"</c>.
/// </summary>
internal sealed class VectorDocument
{
    /// <summary>The QLNet release the vectors are generated by, the package the lock file pins.</summary>
    public const string QLNet = "1.13.2";

    /// <summary>The seed every generator writes, <c>vectors.py</c>'s.</summary>
    public const long Seed = 20261016;

    private const int MaxBytes = 1024 * 1024;

    private readonly string upstream;
    private readonly string path;
    private readonly List<Obj> cases = [];

    /// <summary>Initializes a new instance of the <see cref="VectorDocument"/> class.</summary>
    /// <param name="path">The file's path under <c>tests/vectors</c> without <c>.json</c>, which is also its shim's
    /// path under <c>tools/vectors/gen</c> without <c>.py</c>.</param>
    /// <param name="upstream">The QLNet file the vectors check.</param>
    public VectorDocument(string path, string upstream)
    {
        this.path = path;
        this.upstream = upstream;
    }

    /// <summary>Adds a case.</summary>
    /// <param name="name">The case's name.</param>
    /// <param name="inputs">Its inputs, <c>settings</c> among them.</param>
    /// <param name="expected">Its outputs.</param>
    public void Case(string name, Obj inputs, Obj expected)
    {
        if (!inputs.Has("settings"))
        {
            throw new InvalidOperationException($"{name}: every case writes its settings");
        }

        cases.Add(new Obj { ["name"] = name, ["inputs"] = inputs, ["expected"] = expected });
    }

    /// <summary>Writes the file under the output root, refusing one over the 1 MiB budget.</summary>
    /// <param name="outRoot">The output root, the repository's <c>tests/vectors</c> or a temporary folder.</param>
    public void Write(string outRoot)
    {
        var doc = new Obj
        {
            ["upstream"] = upstream,
            ["qlnet"] = QLNet,
            ["generator"] = "tools/vectors/gen/" + path + ".py",
            ["seed"] = Seed,
            ["cases"] = cases,
        };
        var text = new StringBuilder();
        Encode(text, doc);
        text.Append('\n');
        byte[] data = new UTF8Encoding(false).GetBytes(text.ToString());
        if (data.Length > MaxBytes)
        {
            throw new InvalidOperationException($"{path}.json is {data.Length} bytes, over the 1 MiB budget");
        }

        string file = Path.Combine(outRoot, Path.Combine(path.Split('/')) + ".json");
        Directory.CreateDirectory(Path.GetDirectoryName(file)!);
        File.WriteAllBytes(file, data);
    }

    /// <summary>A real as Python's <c>repr</c> writes it: its shortest round-trip digits, positional when the decimal
    /// point falls within 16 digits of them and with <c>.0</c> on an integer, otherwise <c>d.ddde±XX</c>.</summary>
    /// <param name="x">A finite real.</param>
    /// <returns>Its text.</returns>
    public static string Real(double x)
    {
        if (x == 0)
        {
            return double.IsNegative(x) ? "-0.0" : "0.0";
        }

        string r = x.ToString("R", CultureInfo.InvariantCulture);
        bool negative = r[0] == '-';
        if (negative)
        {
            r = r[1..];
        }

        int exponent = 0;
        int e = r.IndexOfAny(['E', 'e']);
        if (e >= 0)
        {
            exponent = int.Parse(r[(e + 1)..], CultureInfo.InvariantCulture);
            r = r[..e];
        }

        int dot = r.IndexOf('.');
        string whole = dot < 0 ? r : r[..dot];
        string digits = whole + (dot < 0 ? string.Empty : r[(dot + 1)..]);
        int point = whole.Length + exponent;
        int leading = 0;
        while (leading < digits.Length - 1 && digits[leading] == '0')
        {
            leading++;
        }

        digits = digits[leading..].TrimEnd('0');
        point -= leading;
        string text;
        if (point > -4 && point <= 16)
        {
            if (point <= 0)
            {
                text = "0." + new string('0', -point) + digits;
            }
            else if (point >= digits.Length)
            {
                text = digits + new string('0', point - digits.Length) + ".0";
            }
            else
            {
                text = digits[..point] + "." + digits[point..];
            }
        }
        else
        {
            int power = point - 1;
            string mantissa = digits.Length == 1 ? digits : digits[0] + "." + digits[1..];
            text = mantissa + "e" + (power < 0 ? "-" : "+")
                + Math.Abs(power).ToString("00", CultureInfo.InvariantCulture);
        }

        return negative ? "-" + text : text;
    }

    private static void Encode(StringBuilder text, object? value)
    {
        switch (value)
        {
            case null:
                text.Append("null");
                break;
            case bool b:
                text.Append(b ? "true" : "false");
                break;
            case int or long:
                text.Append(Convert.ToString(value, CultureInfo.InvariantCulture));
                break;
            case double d when double.IsNaN(d):
                text.Append("\"NaN\"");
                break;
            case double d when double.IsInfinity(d):
                text.Append(d > 0 ? "\"Infinity\"" : "\"-Infinity\"");
                break;
            case double d:
                text.Append(Real(d));
                break;
            case string s:
                String(text, s);
                break;
            case Obj o:
                text.Append('{');
                bool first = true;
                foreach ((string key, object? v) in o.Entries)
                {
                    text.Append(first ? string.Empty : ",");
                    first = false;
                    String(text, key);
                    text.Append(':');
                    Encode(text, v);
                }

                text.Append('}');
                break;
            case IEnumerable items:
                text.Append('[');
                bool firstItem = true;
                foreach (object? item in items)
                {
                    text.Append(firstItem ? string.Empty : ",");
                    firstItem = false;
                    Encode(text, item);
                }

                text.Append(']');
                break;
            default:
                throw new InvalidOperationException($"no vector encoding for {value.GetType().Name}");
        }
    }

    /// <summary>A string as Python's <c>json.dumps</c> writes it with <c>ensure_ascii=False</c>.</summary>
    private static void String(StringBuilder text, string s)
    {
        text.Append('"');
        foreach (char c in s)
        {
            switch (c)
            {
                case '"': text.Append("\\\""); break;
                case '\\': text.Append("\\\\"); break;
                case '\n': text.Append("\\n"); break;
                case '\r': text.Append("\\r"); break;
                case '\t': text.Append("\\t"); break;
                case '\b': text.Append("\\b"); break;
                case '\f': text.Append("\\f"); break;
                default:
                    if (c < ' ')
                    {
                        text.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        text.Append(c);
                    }

                    break;
            }
        }

        text.Append('"');
    }
}
