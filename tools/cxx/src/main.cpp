// cxx-harness: QuantLib built from its pinned sources, called through JSON-RPC 2.0 over JSON Lines
// (docs/porting-playbook.md §7.1). Each line of standard input is one request,
//     {"jsonrpc": "2.0", "id": <n>, "method": <name>, "params": [...]},
// and each gets one line on standard output, {"jsonrpc": "2.0", "id": <n>, "result": <value>} or
// {"jsonrpc": "2.0", "id": <n>, "error": {"code": <c>, "message": <m>}}.
//
// An exception from the QuantLib call, the construction of QuantLib values from the arguments included, is classed
// as the wheel's handler classes it (QuantLib-SWIG's %exception): code 1 for a QuantLib::Error, 2 for any other
// std::exception and for a throw that is no std::exception (SWIG's "unknown error"), and 3 for std::out_of_range,
// which the wheel raises as IndexError. A failure of the harness itself uses JSON-RPC's codes: -32700 parse error,
// -32600 invalid request, -32601 method not found, -32602 invalid params (the check, and the harness's own
// InvalidParams wherever it is raised), -32603 internal error. NaN and the infinities travel as the bare tokens
// NaN, Infinity and -Infinity, and numbers are parsed exactly.

#include "convert.hpp"

#include <ql/errors.hpp>
#include <ql/version.hpp>

#include <boost/version.hpp>

#include <fcntl.h>
#include <io.h>

#include <cstdio>
#include <iostream>
#include <limits>

const char* harnessSourceDigest();  // generated by CMakeLists.txt

using namespace harness;

namespace {

    // The code options QuantLib's config.hpp can define (ql/config.hpp.cfg); the version reports those defined.
    json::array options() {
        json::array o;
#ifdef QL_ENABLE_PARALLEL_UNIT_TEST_RUNNER
        o.emplace_back("QL_ENABLE_PARALLEL_UNIT_TEST_RUNNER");
#endif
#ifdef QL_ENABLE_SESSIONS
        o.emplace_back("QL_ENABLE_SESSIONS");
#endif
#ifdef QL_ENABLE_THREAD_SAFE_OBSERVER_PATTERN
        o.emplace_back("QL_ENABLE_THREAD_SAFE_OBSERVER_PATTERN");
#endif
#ifdef QL_ENABLE_TRACING
        o.emplace_back("QL_ENABLE_TRACING");
#endif
#ifdef QL_ERROR_FUNCTIONS
        o.emplace_back("QL_ERROR_FUNCTIONS");
#endif
#ifdef QL_ERROR_LINES
        o.emplace_back("QL_ERROR_LINES");
#endif
#ifdef QL_EXTRA_SAFETY_CHECKS
        o.emplace_back("QL_EXTRA_SAFETY_CHECKS");
#endif
#ifdef QL_HIGH_RESOLUTION_DATE
        o.emplace_back("QL_HIGH_RESOLUTION_DATE");
#endif
#ifdef QL_FASTER_LAZY_OBJECTS
        o.emplace_back("QL_FASTER_LAZY_OBJECTS");
#endif
#ifdef QL_THROW_IN_CYCLES
        o.emplace_back("QL_THROW_IN_CYCLES");
#endif
#ifdef QL_USE_INDEXED_COUPON
        o.emplace_back("QL_USE_INDEXED_COUPON");
#endif
#ifdef QL_USE_STD_SHARED_PTR
        o.emplace_back("QL_USE_STD_SHARED_PTR");
#endif
#ifdef QL_NULL_AS_FUNCTIONS
        o.emplace_back("QL_NULL_AS_FUNCTIONS");
#endif
        return o;
    }

    // The harness's own methods; the last three exist for tools/vectors/cxx.py's self-test.
    const Register own({
        {"harness.version",
         [](const Args& a) -> Call {
             arity(a, 0);
             return [] {
                 return json::value(json::object{{"quantlib", QL_VERSION},
                                                 {"boost", BOOST_LIB_VERSION},
                                                 {"msc", _MSC_VER},
                                                 {"mscFull", _MSC_FULL_VER},
                                                 {"options", options()},
                                                 {"source", harnessSourceDigest()}});
             };
         }},
        {"harness.echo",
         [](const Args& a) -> Call {
             arity(a, 1);
             QuantLib::Real x = real(a[0]);
             return [x] { return json::value(x); };
         }},
        {"harness.throwOutOfRange",
         [](const Args& a) -> Call {
             arity(a, 0);
             return []() -> json::value { throw std::out_of_range("a std::out_of_range thrown by the harness"); };
         }},
        {"harness.throwNonStd",
         [](const Args& a) -> Call {
             arity(a, 0);
             return []() -> json::value { throw 42; };
         }},
        {"harness.throwInvalidParamsInCall",
         [](const Args& a) -> Call {
             arity(a, 0);
             return []() -> json::value { throw InvalidParams("the harness's own exception, raised inside the call"); };
         }},
    });

    json::object failure(const json::value& id, int code, const std::string& message) {
        return {{"jsonrpc", "2.0"}, {"id", id}, {"error", json::object{{"code", code}, {"message", message}}}};
    }

    json::object respond(const std::string& line) {
        json::parse_options parsing;
        parsing.numbers = json::number_precision::precise;
        parsing.allow_infinity_and_nan = true;
        boost::system::error_code ec;
        json::value request = json::parse(line, ec, {}, parsing);
        if (ec)
            return failure(nullptr, -32700, "Parse error: " + ec.message());
        const json::object* r = request.if_object();
        const json::value* id = r != nullptr ? r->if_contains("id") : nullptr;
        const json::value rid = id != nullptr ? *id : json::value(nullptr);
        const json::value* version = r != nullptr ? r->if_contains("jsonrpc") : nullptr;
        const json::value* method = r != nullptr ? r->if_contains("method") : nullptr;
        if (version == nullptr || *version != "2.0" || method == nullptr || !method->is_string() || id == nullptr ||
            !(id->is_int64() || id->is_string()))
            return failure(rid, -32600, "Invalid Request");
        auto found = methods().find(std::string(method->get_string()));
        if (found == methods().end())
            return failure(rid, -32601, "Method not found: " + std::string(method->get_string()));
        static const json::array none;
        const json::value* params = r->if_contains("params");
        if (params != nullptr && !params->is_array())
            return failure(rid, -32602, "Invalid params: params must be an array");

        Call call;
        try {
            call = found->second(params != nullptr ? params->get_array() : none);
        } catch (const std::exception& e) {
            // InvalidParams, and Boost.JSON's own access errors.
            return failure(rid, -32602, std::string("Invalid params: ") + e.what());
        } catch (...) {
            return failure(rid, -32603, "Internal error: a non-standard exception in the check");
        }

        try {
            return {{"jsonrpc", "2.0"}, {"id", rid}, {"result", call()}};
        } catch (const InvalidParams& e) {
            return failure(rid, -32602, std::string("Invalid params: ") + e.what());
        } catch (const QuantLib::Error& e) {
            return failure(rid, 1, e.what());
        } catch (const std::out_of_range& e) {
            return failure(rid, 3, e.what());
        } catch (const std::exception& e) {
            return failure(rid, 2, e.what());
        } catch (...) {
            return failure(rid, 2, "unknown error");
        }
    }

}

int main() {
    _setmode(_fileno(stdin), _O_BINARY);
    _setmode(_fileno(stdout), _O_BINARY);
    std::ios::sync_with_stdio(false);
    json::serialize_options writing;
    writing.allow_infinity_and_nan = true;
    std::string line;
    while (std::getline(std::cin, line)) {
        std::string out;
        try {
            out = json::serialize(respond(line), writing);
        } catch (const std::exception& e) {
            out = json::serialize(failure(nullptr, -32603, std::string("Internal error: ") + e.what()), writing);
        }
        std::cout << out << '\n' << std::flush;
    }
    return 0;
}
